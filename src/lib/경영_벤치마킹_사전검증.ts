export const 사전검증_항목 = ['정부_출연금', '정부_보조금', '지자체_출연금', '지자체_보조금', '의료수익', '의료비용', '인건비'] as const;
export type 사전검증_항목_키 = (typeof 사전검증_항목)[number];

export interface 사전검증_결과 {
  수준: '오류의심' | '검토요청';
  규칙: string;
  내용: string;
}

const 천원 = (v: number) => `${Math.round(v).toLocaleString()}천원`;

/** 공시값 자체 점검 + ERP 입력값 대조 */
export function 공시_사전검증(공시: 알리미_연도별_공시, erp: Partial<Record<사전검증_항목_키, number | null>>): 사전검증_결과[] {
  const out: 사전검증_결과[] = [];
  const g출 = 공시.정부_출연금, j출 = 공시.지자체_출연금, g보 = 공시.정부_보조금, j보 = 공시.지자체_보조금;
  if (g출 && j출 && g출 === j출)
    out.push({ 수준: '오류의심', 규칙: '출연금 이중기재·혼입', 내용: `정부지원 출연금과 지자체지원 출연금이 ${천원(g출)}으로 같습니다. 같은 출연금을 양쪽에 기재했는지 확인하세요.` });
  if (g보 && j보 && g보 === j보)
    out.push({ 수준: '오류의심', 규칙: '보조금 이중기재·혼입', 내용: `정부지원 보조금과 지자체지원 보조금이 ${천원(g보)}으로 같습니다.` });
  const 소계합 = (공시.정부지원금 ?? 0) + (공시.지자체지원금 ?? 0);
  if (공시.정부지자체_합계 !== null && Math.abs(공시.정부지자체_합계 - 소계합) > 2)
    out.push({ 수준: '오류의심', 규칙: '지원금 합계 불일치', 내용: `정부·지자체 지원 소계 ${천원(공시.정부지자체_합계)} ≠ 정부 ${천원(공시.정부지원금 ?? 0)} + 지자체 ${천원(공시.지자체지원금 ?? 0)}` });
  // 출연금↔보조금 맞바뀜 (ERP 기준)
  for (const 주체 of ['정부', '지자체'] as const) {
    const 공출 = 공시[`${주체}_출연금`], 공보 = 공시[`${주체}_보조금`];
    const e출 = erp[`${주체}_출연금`], e보 = erp[`${주체}_보조금`];
    if (공출 && 공보 && e출 != null && e보 != null && 공출 !== 공보 && 공출 === e보 && 공보 === e출)
      out.push({ 수준: '오류의심', 규칙: '출연금·보조금 계정 혼입', 내용: `${주체} 출연금과 보조금이 ERP와 서로 바뀌어 공시되었습니다 (공시 출연금 ${천원(공출)} = ERP 보조금).` });
  }
  // ERP 대조
  for (const k of 사전검증_항목) {
    const 공 = 공시[k];
    const e = erp[k];
    if (공 === null || e === null || e === undefined) continue;
    const 차 = 공 - e;
    if (Math.abs(차) > 2)
      out.push({ 수준: Math.abs(차) / Math.max(1, Math.abs(e)) > 0.15 ? '오류의심' : '검토요청', 규칙: 'ERP 대조 불일치', 내용: `${k.replace('_', ' ')}: 공시 ${천원(공)} vs ERP ${천원(e)} (차이 ${천원(차)})` });
  }
  return out;
}

