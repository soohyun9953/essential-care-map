/** 규칙: 야간(22~06시) 민감정보 대량조회(50건 이상) / 업무 무관 민감정보 조회 / 야간 민감정보 조회 */
export function 이상접근_탐지(로그: 접근_로그[]) {
  return 로그.flatMap((l) => {
    const 시 = Number(l.시각.slice(0, 2));
    const 야간 = 시 >= 22 || 시 < 6;
    const out: { 사용자: string; 수준: '경고' | '주의'; 사유: string }[] = [];
    if (l.대상 === '민감정보' && 야간 && l.조회건수 >= 50) out.push({ 사용자: l.사용자, 수준: '경고', 사유: `야간 ${l.시각} 민감정보 ${l.조회건수}건 대량 조회` });
    else if (l.대상 === '민감정보' && 야간) out.push({ 사용자: l.사용자, 수준: '주의', 사유: `야간 ${l.시각} 민감정보 조회` });
    if (l.대상 === '민감정보' && !l.업무관련) out.push({ 사용자: l.사용자, 수준: '경고', 사유: '업무 무관 민감정보 조회' });
    return out;
  });
}
