export async function diagnoseEssentialCareRegion(params: { sgg: string }) {
  const cleanSgg = params.sgg.trim();
  const raw = RAW_REGIONS_MAP[cleanSgg] || {
    시도명: '기타 시도',
    시군구명: cleanSgg,
    인구수: 45000,
    응급_60분_미도달_인구비율: 55.0,
    관내_응급_의료이용률: 24.0,
    분만_60분_미도달_인구비율: 60.0,
    관내_분만율: 20.0,
    소아_병상_공급비율: 30.0,
    소아_야간휴일_접근성지수: 20.0,
  };

  // 법정 기준 판정
  const isEmergencyVuln = raw.응급_60분_미도달_인구비율 > 30 || raw.관내_응급_의료이용률 < 30;
  const isDeliveryVuln = raw.분만_60분_미도달_인구비율 > 30 || raw.관내_분만율 < 40;
  const isPediatricVuln = raw.소아_병상_공급비율 < 60;

  const count = [isEmergencyVuln, isDeliveryVuln, isPediatricVuln].filter(Boolean).length;

  let grade: '정상' | '관찰' | '취약' | '심각' = '정상';
  if (count === 3) grade = '심각';
  else if (count === 2) grade = '취약';
  else if (count === 1) grade = '관찰';

  const score = Math.round(
    raw.응급_60분_미도달_인구비율 * 0.4 +
    (100 - raw.관내_응급_의료이용률) * 0.3 +
    (100 - raw.소아_병상_공급비율) * 0.3
  );

  return {
    지자체: `${raw.시도명} ${raw.시군구명}`,
    인구수: `${raw.인구수.toLocaleString()}명`,
    종합_취약도_등급: grade,
    종합_취약도_점수: `${score}점 (100점 만점, 높을수록 위험)`,
    취약분야_수: `${count}개 분야 취약 (총 3개 중)`,
    법정_분야별_판정결과: {
      응급의료: {
        취약여부: isEmergencyVuln ? '취약 (법정 기준 미달)' : '적정',
        지표: `60분 미도달 ${raw.응급_60분_미도달_인구비율}% (> 30%), 관내이용률(RI) ${raw.관내_응급_의료이용률}% (< 30%)`,
      },
      분만_모자의료: {
        취약여부: isDeliveryVuln ? '취약 (법정 기준 미달)' : '적정',
        지표: `60분 미도달 ${raw.분만_60분_미도달_인구비율}% (> 30%), 관내분만율 ${raw.관내_분만율}% (< 40%)`,
      },
      소아_중증진료: {
        취약여부: isPediatricVuln ? '취약 (법정 기준 미달)' : '적정',
        지표: `기준병상 대비 공급비율 ${raw.소아_병상_공급비율}% (< 60%)`,
      },
    },
    정부_지원_우선순위:
      grade === '심각'
        ? '보건복지부 취약지 지원사업 최우선 국비 배정 권고 대상'
        : grade === '취약'
        ? '보건복지부 공모사업 중점 지원 대상'
        : '관찰 및 집중 모니터링 대상',
  };
}
