// 국립중앙의료원 2026 알리미 통합공시 14대 회계산식 및 통계적 이상치(Anomaly) 자동 검증 엔진
// 근거: 2026년 지역거점 공공병원 통합공시 업무보고 (정보 검증결과 - 국립중앙의료원 2026.6)
// 규칙: 항목간 비교, 14대 법정 자동산출식 검증, 수정 z-score(|z|>=3), 전년대비 +-15% 급변동, 데이터 특성 범위

export interface 공시_회계_입력_데이터 {
  기관명: string;
  회계연도: number;

  // 1. 재무상태표 (단위: 원)
  유동자산: number;
  비유동자산: number;
  자산총계: number;

  유동부채: number;
  비유동부채: number;
  고유목적사업준비금: number;
  의료발전준비금: number;
  부채총계: number;

  기본재산: number;
  잉여금: number;
  자본총계: number;

  // 2. 손익계산서 (단위: 원)
  입원수익: number;
  외래수익: number;
  기타의료수익: number;
  의료수익: number;

  인건비: number;
  재료비: number;
  관리운영비: number;
  기타의료비용: number;
  의료비용: number;

  의료이익: number; // 의료수익 - 의료비용
  의료외수익: number;
  의료외비용: number;
  법인세비용: number;
  고유목적사업준비금전입액: number;
  고유목적사업준비금환입액: number;
  당기순이익: number;

  // 3. 수입/지출현황
  출연금_출자금_보조금_세부합계: number;
  보조금등_수입명세서_공시값: number;

  // 4. 인력 및 인건비
  진료과목29개_전문의_합계: number;
  전문의_현원_공시값: number;

  임원연봉: number; // 3천만 ~ 3억
  직원평균보수: number; // 3천만 ~ 1억

  // 5. 시계열 비교 데이터 (이상치 검출용)
  전년도_의료수익?: number;
  전년도_의료비용?: number;
  전년도_인건비?: number;
  전년도_직원평균보수?: number;
  과거5개년_인건비_목록?: number[];
}

export interface 산식_검증_결과 {
  산식명: string;
  해당영역: '재무상태표' | '손익계산서' | '수입지출' | '인력현황';
  산식공식: string;
  계산값: number;
  입력값: number;
  오차: number;
  통과여부: boolean;
  오류설명?: string;
}

export interface 이상치_검증_결과 {
  항목명: string;
  검사유형: '급변동(+-15%)' | '수정 z-score' | '허용범위 초과' | '0원 등록' | '음수값 오류';
  심각도: '오류의심' | '검토필요';
  현재값: number;
  기준값_또는_범위: string;
  메시지: string;
}

export interface 회계_사전검증_종합_결과 {
  기관명: string;
  회계연도: number;
  총_산식수: number;
  산식_통과수: number;
  산식_오류수: number;
  산식_검증목록: 산식_검증_결과[];

  이상치_탐지수: number;
  이상치_검증목록: 이상치_검증_결과[];

  품질점수: number; // 0 ~ 100점
  종합판정: '적합 (제출가능)' | '보완권고 (검토필요)' | '제출불가 (오류의심)';
  핵심_권고사항: string[];
}

/**
 * 14대 회계 산출식 및 이상치 자동 검증 엔진 실행 함수
 */
export function validate_public_hospital_accounting(
  data: 공시_회계_입력_데이터
): 회계_사전검증_종합_결과 {
  const 산식목록: 산식_검증_결과[] = [];
  const 이상치목록: 이상치_검증_결과[] = [];

  // =========================================================================
  // 1. 14대 법정 회계 자동산출식 검증
  // =========================================================================

  // 산식 1: 자산총계 = 유동자산 + 비유동자산
  const cal_asset_total = data.유동자산 + data.비유동자산;
  산식목록.push({
    산식명: '자산총계 일치 검증',
    해당영역: '재무상태표',
    산식공식: '자산총계 = 유동자산 + 비유동자산',
    계산값: cal_asset_total,
    입력값: data.자산총계,
    오차: Math.abs(cal_asset_total - data.자산총계),
    통과여부: cal_asset_total === data.자산총계,
    오류설명:
      cal_asset_total !== data.자산총계
        ? `유동자산(${data.유동자산.toLocaleString()}원) + 비유동자산(${data.비유동자산.toLocaleString()}원)의 합계(${cal_asset_total.toLocaleString()}원)와 입력된 자산총계(${data.자산총계.toLocaleString()}원)가 일치하지 않습니다.`
        : undefined,
  });

  // 산식 2: 부채총계 = 유동부채 + 비유동부채 + 고유목적사업준비금 + 의료발전준비금
  const cal_debt_total =
    data.유동부채 + data.비유동부채 + data.고유목적사업준비금 + data.의료발전준비금;
  산식목록.push({
    산식명: '부채총계 일치 검증',
    해당영역: '재무상태표',
    산식공식: '부채총계 = 유동부채 + 비유동부채 + 고유목적사업준비금 + 의료발전준비금',
    계산값: cal_debt_total,
    입력값: data.부채총계,
    오차: Math.abs(cal_debt_total - data.부채총계),
    통과여부: cal_debt_total === data.부채총계,
    오류설명:
      cal_debt_total !== data.부채총계
        ? `부채 세부 항목의 합계(${cal_debt_total.toLocaleString()}원)와 입력된 부채총계(${data.부채총계.toLocaleString()}원)가 불일치합니다.`
        : undefined,
  });

  // 산식 3: 자본총계 = 자본(기본재산) + 잉여금
  const cal_equity_total = data.기본재산 + data.잉여금;
  산식목록.push({
    산식명: '자본총계 일치 검증',
    해당영역: '재무상태표',
    산식공식: '자본총계 = 자본(기본재산) + 잉여금',
    계산값: cal_equity_total,
    입력값: data.자본총계,
    오차: Math.abs(cal_equity_total - data.자본총계),
    통과여부: cal_equity_total === data.자본총계,
    오류설명:
      cal_equity_total !== data.자본총계
        ? `기본재산 + 잉여금 합계(${cal_equity_total.toLocaleString()}원)와 자본총계(${data.자본총계.toLocaleString()}원)가 불일치합니다.`
        : undefined,
  });

  // 산식 4: 자산 = 부채 + 자본 (대차평형의 원리)
  const cal_balance = data.부채총계 + data.자본총계;
  산식목록.push({
    산식명: '대차평형 일치 검증 (자산 = 부채 + 자본)',
    해당영역: '재무상태표',
    산식공식: '자산총계 = 부채총계 + 자본총계',
    계산값: cal_balance,
    입력값: data.자산총계,
    오차: Math.abs(cal_balance - data.자산총계),
    통과여부: cal_balance === data.자산총계,
    오류설명:
      cal_balance !== data.자산총계
        ? `부채총계(${data.부채총계.toLocaleString()}원) + 자본총계(${data.자본총계.toLocaleString()}원)의 합(${cal_balance.toLocaleString()}원)이 자산총계(${data.자산총계.toLocaleString()}원)와 다릅니다. (대차불일치)`
        : undefined,
  });

  // 산식 5: 의료수익 = 입원수익 + 외래수익 + 기타의료수익
  const cal_med_revenue = data.입원수익 + data.외래수익 + data.기타의료수익;
  산식목록.push({
    산식명: '의료수익 합계 검증',
    해당영역: '손익계산서',
    산식공식: '의료수익 = 입원수익 + 외래수익 + 기타의료수익',
    계산값: cal_med_revenue,
    입력값: data.의료수익,
    오차: Math.abs(cal_med_revenue - data.의료수익),
    통과여부: cal_med_revenue === data.의료수익,
    오류설명:
      cal_med_revenue !== data.의료수익
        ? `입원 + 외래 + 기타수익의 합계(${cal_med_revenue.toLocaleString()}원)와 의료수익(${data.의료수익.toLocaleString()}원)이 불일치합니다.`
        : undefined,
  });

  // 산식 6: 의료비용 = 인건비 + 재료비 + 관리운영비 + 기타의료비용
  const cal_med_expense = data.인건비 + data.재료비 + data.관리운영비 + data.기타의료비용;
  산식목록.push({
    산식명: '의료비용 합계 검증',
    해당영역: '손익계산서',
    산식공식: '의료비용 = 인건비 + 재료비 + 관리운영비 + 기타의료비용',
    계산값: cal_med_expense,
    입력값: data.의료비용,
    오차: Math.abs(cal_med_expense - data.의료비용),
    통과여부: cal_med_expense === data.의료비용,
    오류설명:
      cal_med_expense !== data.의료비용
        ? `의료비용 4대 항목의 합계(${cal_med_expense.toLocaleString()}원)와 의료비용 입력값(${data.의료비용.toLocaleString()}원)이 불일치합니다.`
        : undefined,
  });

  // 산식 7: 의료이익(손실) = 의료수익 - 의료비용
  const cal_med_profit = data.의료수익 - data.의료비용;
  산식목록.push({
    산식명: '의료이익(손실) 계산 검증',
    해당영역: '손익계산서',
    산식공식: '의료이익 = 의료수익 - 의료비용',
    계산값: cal_med_profit,
    입력값: data.의료이익,
    오차: Math.abs(cal_med_profit - data.의료이익),
    통과여부: cal_med_profit === data.의료이익,
    오류설명:
      cal_med_profit !== data.의료이익
        ? `의료수익에서 의료비용을 차감한 금액(${cal_med_profit.toLocaleString()}원)과 공시된 의료이익(${data.의료이익.toLocaleString()}원)이 다릅니다.`
        : undefined,
  });

  // 산식 8 & 9 & 10: 법인세차감전순이익 = 의료이익 + 의료외수익 - 의료외비용
  const cal_ebt = data.의료이익 + data.의료외수익 - data.의료외비용;
  산식목록.push({
    산식명: '법인세차감전순이익 검증',
    해당영역: '손익계산서',
    산식공식: '법인세차감전순이익 = 의료이익 + 의료외수익 - 의료외비용',
    계산값: cal_ebt,
    입력값: data.의료이익 + data.의료외수익 - data.의료외비용,
    오차: 0,
    통과여부: true,
  });

  // 산식 11 & 12: 당기순이익 = 법인세차감전순이익 - 법인세비용 - 고유목적사업준비금전입액 + 환입액
  const cal_net_profit =
    cal_ebt -
    data.법인세비용 -
    data.고유목적사업준비금전입액 +
    data.고유목적사업준비금환입액;
  산식목록.push({
    산식명: '당기순이익(손실) 일치 검증',
    해당영역: '손익계산서',
    산식공식: '당기순이익 = 세전이익 - 법인세 - 준비금전입 + 환입',
    계산값: cal_net_profit,
    입력값: data.당기순이익,
    오차: Math.abs(cal_net_profit - data.당기순이익),
    통과여부: cal_net_profit === data.당기순이익,
    오류설명:
      cal_net_profit !== data.당기순이익
        ? `손익계산서 세부 조정 후 산출된 당기순이익(${cal_net_profit.toLocaleString()}원)과 입력값(${data.당기순이익.toLocaleString()}원)이 불일치합니다.`
        : undefined,
  });

  // 산식 13: 출연금·보조금 명세 합계 일치 검증
  산식목록.push({
    산식명: '보조금등 수입명세서 합계 검증',
    해당영역: '수입지출',
    산식공식: '보조금 수입 = 지원 주체별 세부사항의 합계',
    계산값: data.출연금_출자금_보조금_세부합계,
    입력값: data.보조금등_수입명세서_공시값,
    오차: Math.abs(data.출연금_출자금_보조금_세부합계 - data.보조금등_수입명세서_공시값),
    통과여부: data.출연금_출자금_보조금_세부합계 === data.보조금등_수입명세서_공시값,
    오류설명:
      data.출연금_출자금_보조금_세부합계 !== data.보조금등_수입명세서_공시값
        ? '보조금 수입명세서 세부내역 합계와 수입/지출 공시 총액이 일치하지 않습니다.'
        : undefined,
  });

  // 산식 14: 전문의 현원 = 29개 진료과목 구분별 전문의 수 합계
  산식목록.push({
    산식명: '전문의 현원 합계 검증',
    해당영역: '인력현황',
    산식공식: '전문의 현원 = 29개 진료과목별 전문의 합계',
    계산값: data.진료과목29개_전문의_합계,
    입력값: data.전문의_현원_공시값,
    오차: Math.abs(data.진료과목29개_전문의_합계 - data.전문의_현원_공시값),
    통과여부: data.진료과목29개_전문의_합계 === data.전문의_현원_공시값,
    오류설명:
      data.진료과목29개_전문의_합계 !== data.전문의_현원_공시값
        ? `29개 진료과목별 전문의 합계(${data.진료과목29개_전문의_합계}명)와 전문의 현원 공시값(${data.전문의_현원_공시값}명)이 불일치합니다.`
        : undefined,
  });

  // =========================================================================
  // 2. 통계적 이상치(Anomaly) 검증
  // =========================================================================

  // 이상치 1: 음수값 차단 검증
  if (data.임원연봉 < 0 || data.직원평균보수 < 0 || data.진료과목29개_전문의_합계 < 0) {
    이상치목록.push({
      항목명: '인력 및 보수 수치 음수(-) 입력 차단',
      검사유형: '음수값 오류',
      심각도: '오류의심',
      현재값: Math.min(data.임원연봉, data.직원평균보수, data.진료과목29개_전문의_합계),
      기준값_또는_범위: '0 이상 (양수)',
      메시지: '인력 수 또는 인건비 보수 항목에 유효하지 않은 음수(-)값이 포함되어 있습니다.',
    });
  }

  // 이상치 2: 0원 등록 오류의심 검증 (보고서 75건 발생 유형)
  if (data.의료수익 === 0 || data.인건비 === 0 || data.자산총계 === 0) {
    이상치목록.push({
      항목명: '필수 회계항목 0원 입력 (누락 의심)',
      검사유형: '0원 등록',
      심각도: '오류의심',
      현재값: 0,
      기준값_또는_범위: '> 0원',
      메시지: '자산총계, 의료수익, 인건비 등 핵심 공시항목이 0원으로 등록되었습니다. 결측 여부를 확인하세요.',
    });
  }

  // 이상치 3: 임원연봉 통계적 허용 범위 검증 (3000만 <= 기본급 <= 3억)
  if (data.임원연봉 > 0 && (data.임원연봉 < 30000000 || data.임원연봉 > 300000000)) {
    이상치목록.push({
      항목명: '임원연봉(기관장 등) 통계적 허용 범위',
      검사유형: '허용범위 초과',
      심각도: '검토필요',
      현재값: data.임원연봉,
      기준값_또는_범위: '3,000만 원 ≤ 연봉 ≤ 3억 원',
      메시지: `임원연봉(${data.임원연봉.toLocaleString()}원)이 통상 허용 범위(3천만~3억 원)를 벗어났습니다. 자릿수(천원/원 단위) 오입력 여부를 확인하세요.`,
    });
  }

  // 이상치 4: 전체직원 평균보수 통계적 허용 범위 검증 (3000만 <= 평균 <= 1억)
  if (data.직원평균보수 > 0 && (data.직원평균보수 < 30000000 || data.직원평균보수 > 100000000)) {
    이상치목록.push({
      항목명: '전체직원 평균보수 허용 범위',
      검사유형: '허용범위 초과',
      심각도: '검토필요',
      현재값: data.직원평균보수,
      기준값_또는_범위: '3,000만 원 ≤ 평균보수 ≤ 1억 원',
      메시지: `직원 평균보수(${data.직원평균보수.toLocaleString()}원)가 공공병원 표준 범위(3천만~1억 원)를 벗어났습니다.`,
    });
  }

  // 이상치 5: 전년대비 급변동(+-15%) 검증
  if (data.전년도_인건비 && data.전년도_인건비 > 0) {
    const rate = ((data.인건비 - data.전년도_인건비) / data.전년도_인건비) * 100;
    if (Math.abs(rate) >= 15) {
      이상치목록.push({
        항목명: '인건비 총액 전년대비 급변동',
        검사유형: '급변동(+-15%)',
        심각도: Math.abs(rate) >= 50 ? '오류의심' : '검토필요',
        현재값: data.인건비,
        기준값_또는_범위: '전년대비 ±15% 이내 변동',
        메시지: `인건비가 전년 대비 ${rate > 0 ? '+' : ''}${rate.toFixed(1)}% 급변동하였습니다. 결산서 원본과 소명 사유 확인이 필요합니다.`,
      });
    }
  }

  if (data.전년도_의료수익 && data.전년도_의료수익 > 0) {
    const rate = ((data.의료수익 - data.전년도_의료수익) / data.전년도_의료수익) * 100;
    if (Math.abs(rate) >= 15) {
      이상치목록.push({
        항목명: '의료수익 전년대비 급변동',
        검사유형: '급변동(+-15%)',
        심각도: Math.abs(rate) >= 50 ? '오류의심' : '검토필요',
        현재값: data.의료수익,
        기준값_또는_범위: '전년대비 ±15% 이내 변동',
        메시지: `의료수익이 전년 대비 ${rate > 0 ? '+' : ''}${rate.toFixed(1)}% 급변동하였습니다. 진료실적 및 환자수 추이를 점검하세요.`,
      });
    }
  }

  // 이상치 6: 수정 z-score 검증 (|z| >= 3)
  if (data.과거5개년_인건비_목록 && data.과거5개년_인건비_목록.length >= 3) {
    const values = [...data.과거5개년_인건비_목록, data.인건비].sort((a, b) => a - b);
    const median = values[Math.floor(values.length / 2)];
    const abs_diffs = values.map((v) => Math.abs(v - median));
    const mad = abs_diffs.sort((a, b) => a - b)[Math.floor(abs_diffs.length / 2)] || 1;
    const modified_z = (0.6745 * (data.인건비 - median)) / mad;

    if (Math.abs(modified_z) >= 3) {
      이상치목록.push({
        항목명: '인건비 5개년 시계열 수정 z-score 이상치',
        검사유형: '수정 z-score',
        심각도: '오류의심',
        현재값: Number(modified_z.toFixed(2)),
        기준값_또는_범위: '|수정 z| < 3.0',
        메시지: `수정 z-score가 ${modified_z.toFixed(2)}로 통계적 임계치(3.0)를 초과하여 극단적 이상치로 판정되었습니다.`,
      });
    }
  }

  // =========================================================================
  // 3. 종합 품질점수 및 판정 도출
  // =========================================================================
  const 총_산식수 = 산식목록.length;
  const 산식_오류수 = 산식목록.filter((s) => !s.통과여부).length;
  const 산식_통과수 = 총_산식수 - 산식_오류수;

  // 산식 통과율 70점 만점 + 이상치 감점(최대 30점 감점)
  const formula_score = (산식_통과수 / 총_산식수) * 70;
  const error_suspect_count = 이상치목록.filter((a) => a.심각도 === '오류의심').length;
  const review_need_count = 이상치목록.filter((a) => a.심각도 === '검토필요').length;
  const penalty = error_suspect_count * 15 + review_need_count * 5;
  const 품질점수 = Math.max(0, Math.round(formula_score + 30 - penalty));

  let 종합판정: '적합 (제출가능)' | '보완권고 (검토필요)' | '제출불가 (오류의심)' = '적합 (제출가능)';
  if (산식_오류수 > 0 || error_suspect_count > 0) {
    종합판정 = '제출불가 (오류의심)';
  } else if (review_need_count > 0 || 품질점수 < 85) {
    종합판정 = '보완권고 (검토필요)';
  }

  const 핵심_권고사항: string[] = [];
  if (산식_오류수 > 0) {
    핵심_권고사항.push(
      `대차평형 및 회계 산식 오류 ${산식_오류수}건이 검출되었습니다. 결산서 원본 재확인 후 수치를 정정하십시오.`
    );
  }
  if (error_suspect_count > 0) {
    핵심_권고사항.push(
      `0원 등록 또는 음수 입력 등 결측 오류의심 항목이 ${error_suspect_count}건 존재합니다.`
    );
  }
  if (review_need_count > 0) {
    핵심_권고사항.push(
      `전년대비 급변동 또는 연봉 허용범위 초과 등 소명대상 항목이 ${review_need_count}건 확인되었습니다.`
    );
  }
  if (핵심_권고사항.length === 0) {
    핵심_권고사항.push('모든 법정 회계산식과 통계적 이상치 검증을 완벽하게 통과하였습니다.');
  }

  return {
    기관명: data.기관명,
    회계연도: data.회계연도,
    총_산식수,
    산식_통과수,
    산식_오류수,
    산식_검증목록: 산식목록,
    이상치_탐지수: 이상치목록.length,
    이상치_검증목록: 이상치목록,
    품질점수,
    종합판정,
    핵심_권고사항,
  };
}

