export function 정보등급_판정(입력: string): { 등급: 정보등급; 사유: string } {
  if (/대외비|기밀|비밀|보안\s*등급|비공개\s*문서/.test(입력)) return { 등급: 'C', 사유: '기밀 표시어 포함' };
  const pii = mask_patient_pii(입력);
  if (pii.총_탐지건수 > 0) return { 등급: 'S', 사유: `개인정보 ${pii.총_탐지건수}건 탐지 (${Array.from(new Set(pii.탐지목록.map((x) => x.유형))).join(', ')})` };
  if (/환자|진료기록|병록|진단명|처방/.test(입력)) return { 등급: 'S', 사유: '진료정보 관련 표현 포함' };
  return { 등급: 'O', 사유: '기밀·개인정보 표현 없음' };
}

