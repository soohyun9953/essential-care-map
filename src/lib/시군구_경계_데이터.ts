/**
 * 지자체명을 기반으로 대표 위경도 좌표를 조회 (폴백 매핑 완비)
 */
export function get_sgg_coordinates(sgg_name: string, sido_name?: string): [number, number] {
  // 1. 대표 좌표 사전에 매칭
  if (전국_시군구_대표_좌표[sgg_name]) {
    return 전국_시군구_대표_좌표[sgg_name];
  }

  // 2. 시군구 경계 데이터셋에서 조회
  if (전국_시군구_위치_데이터[sgg_name]) {
    return [전국_시군구_위치_데이터[sgg_name].위도, 전국_시군구_위치_데이터[sgg_name].경도];
  }

  // 3. '구'나 '시' 명칭 접미사 처리 (예: 제천 -> 제천시, 원주 -> 원주시)
  for (const [key, coords] of Object.entries(전국_시군구_대표_좌표)) {
    if (key.startsWith(sgg_name) || sgg_name.startsWith(key)) {
      return coords;
    }
  }

  // 4. 중진료권 중심 좌표로 폴백
  for (const zone of Object.values(전국_70개_중진료권_데이터)) {
    if (zone.포함_시군구.includes(sgg_name) || zone.중진료권명.includes(sgg_name)) {
      return [zone.위도, zone.경도];
    }
  }

  // 5. 최종 시도 기본 좌표 (대한민국 중심부 대전 인근 기본값)
  if (sido_name?.includes('강원')) return [37.8228, 128.1555];
  if (sido_name?.includes('서울')) return [37.5665, 126.9780];
  if (sido_name?.includes('충북')) return [36.8000, 127.7000];
  if (sido_name?.includes('충남')) return [36.6588, 126.6728];
  if (sido_name?.includes('전북')) return [35.7175, 127.1530];
  if (sido_name?.includes('전남')) return [34.8160, 126.4630];
  if (sido_name?.includes('경북')) return [36.5760, 128.5056];
  if (sido_name?.includes('경남')) return [35.2383, 128.6924];
  if (sido_name?.includes('경기')) return [37.4138, 127.5183];
  if (sido_name?.includes('인천')) return [37.4563, 126.7052];
  if (sido_name?.includes('부산')) return [35.1796, 129.0756];
  if (sido_name?.includes('대구')) return [35.8714, 128.6014];
  if (sido_name?.includes('광주')) return [35.1595, 126.8526];
  if (sido_name?.includes('대전')) return [36.3504, 127.3845];
  if (sido_name?.includes('울산')) return [35.5384, 129.3114];
  if (sido_name?.includes('세종')) return [36.4800, 127.2890];
  if (sido_name?.includes('제주')) return [33.4996, 126.5312];

  return [36.5, 127.8];
}

/**
 * 시군구명으로 위치 및 폴리곤 데이터를 조회하는 헬퍼 함수
 * 등록되지 않은 지자체라도 대표 좌표를 통해 절대 null을 반환하지 않음
 */
export function get_region_location(sgg_name: string, sido_name?: string): 시군구_위치_정보 | null {
  if (!sgg_name) return null;

  if (전국_시군구_위치_데이터[sgg_name]) {
    return 전국_시군구_위치_데이터[sgg_name];
  }
  // 부분 일치 검색
  for (const key of Object.keys(전국_시군구_위치_데이터)) {
    if (sgg_name.includes(key) || key.includes(sgg_name)) {
      return 전국_시군구_위치_데이터[key];
    }
  }

  // 3. 전국 시군구 대표 좌표 사전 폴백 (폴리곤은 빈 배열이지만 정확한 위경도 좌표 제공)
  const coords = get_sgg_coordinates(sgg_name, sido_name);
  if (coords) {
    return {
      시군구명: sgg_name,
      시도명: sido_name || '',
      위도: coords[0],
      경도: coords[1],
      폴리곤_좌표: [],
    };
  }

  return null;
}
