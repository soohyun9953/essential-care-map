export interface 장비_대장 {
  장비명: string;
  분야: string;
  도입연도: number;
  내용연수: number; // 기관 자산 대장 기준 (연)
  가동률_pct: number; // 기관 입력
  필수의료_연관: boolean;
}

export interface 장비_진단 extends 장비_대장 {
  경과연수: number;
  초과연수: number;
  우선순위_점수: number;
  권고: string;
}

/** 우선순위 점수 = 내용연수 초과연수×20 + 가동률 70% 이상이면 +20 + 필수의료 연관 +30 (플랫폼 규칙) */
export function 장비_노후도_진단(대장: 장비_대장[], 기준연도: number): 장비_진단[] {
  return 대장
    .map((e) => {
      const 경과연수 = 기준연도 - e.도입연도;
      const 초과연수 = Math.max(0, 경과연수 - e.내용연수);
      const 점수 = 초과연수 * 20 + (e.가동률_pct >= 70 ? 20 : 0) + (e.필수의료_연관 ? 30 : 0);
      const 권고 =
        초과연수 > 0
          ? `내용연수 +${초과연수}년 초과${e.가동률_pct >= 70 ? '·고가동' : ''} → 차년도 기능보강 교체 신청 검토`
          : 경과연수 >= e.내용연수 - 1
            ? '내용연수 도래 예정 → 차차년도 교체 계획 수립'
            : '정상 사용';
      return { ...e, 경과연수, 초과연수, 우선순위_점수: 점수, 권고 };
    })
    .sort((a, b) => b.우선순위_점수 - a.우선순위_점수);
}

