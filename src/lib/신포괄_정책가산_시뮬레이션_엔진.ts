export class 신포괄_정책가산_시뮬레이션_엔진 {
  // 규모별 최소 필요 CP 질환 수 기준
  static get_min_cp_required(scale: 병원_규모_구분): number {
    switch (scale) {
      case '종합병원_500병상_초과':
        return 15;
      case '종합병원_300병상_초과':
        return 10;
      case '종합병원_300병상_이하':
        return 7;
      case '병원급':
        return 5;
    }
  }

  // 시뮬레이션 계산 실행
  static calculate(
    scale: 병원_규모_구분,
    annual_revenue_billion: number,
    checklist: CP_개발_체크리스트,
    usage: CP_적용_실적_입력
  ): 시뮬레이션_결과_보고서 {
    const min_cp = this.get_min_cp_required(scale);

    // 1. ㉠ 개발 영역 점수 산출 (50점 만점)
    // 16개 항목 중 충족된 항목 수 비율
    const checklist_values = Object.values(checklist);
    const passed_count = checklist_values.filter(Boolean).length;
    const total_checklist_items = checklist_values.length; // 16개
    const dev_score = Math.round((passed_count / total_checklist_items) * 50 * 10) / 10;

    // 2. ㉡ 적용 영역 점수 산출 (50점 만점)
    // ⓐ 적용 현황 (20점 만점)
    let apply_status_score = 0;
    if (usage.운영_CP_개수 >= min_cp) {
      apply_status_score = 20;
    } else {
      apply_status_score = Math.round((usage.운영_CP_개수 / min_cp) * 20 * 10) / 10;
    }

    // ⓑ 질환별 적용 (10점 만점)
    const apply_rate = usage.대상_환자건수 > 0
      ? Math.min(100, Math.round((usage.적용_환자건수 / usage.대상_환자건수) * 100 * 10) / 10)
      : 0;
    const complete_rate = usage.적용_환자건수 > 0
      ? Math.min(100, Math.round((usage.완료_환자건수 / usage.적용_환자건수) * 100 * 10) / 10)
      : 0;

    // 플랫폼 가정: (적용률 + 완료율)/2 비례 — 원문은 산출 항목만 제시(시범 지표)
    const apply_metric_score = Math.min(
      10,
      Math.round(((apply_rate * 0.5 + complete_rate * 0.5) / 100) * 10 * 10) / 10
    );

    // ⓒ 질환별 관리율 (5점 만점)
    const mgmt_rate = usage.운영_CP_개수 > 0
      ? Math.min(100, Math.round((usage.모니터링_보고_CP_개수 / usage.운영_CP_개수) * 100 * 10) / 10)
      : 0;
    const mgmt_score = Math.round((mgmt_rate / 100) * 5 * 10) / 10;

    // ⓓ 대표 5개 CP 성과 모니터링 (15점 만점)
    const monitor_score = usage.대표_5개_CP_지표평가_보고 ? 15 : 0;

    const apply_score = Math.round((apply_status_score + apply_metric_score + mgmt_score + monitor_score) * 10) / 10;

    // 종합 100점 만점 환산
    const total_score = Math.min(100, Math.round((dev_score + apply_score) * 10) / 10);

    // 운영평가 등급: 원문(사업 안내서)에 점수 구간별 등급이 없어 산출하지 않음
    const grade = '등급 기준 없음 (점수만 산출)';

    // 신포괄 정책가산율: 가산율 1.0%(별표3) × 점수 비례 (사업 안내서 '가산율 적용방법: 비례방식')
    const incentive_rate = Math.round(CP_운영_가산율_최대 * (total_score / 100) * 1000) / 1000;

    // 가산수가 = 가산율 × 포괄수가 (지침 35쪽). 입력값은 연간 포괄수가 총액(억원) → 만원 단위
    const annual_incentive_ten_thousand_won = Math.round(annual_revenue_billion * 10000 * (incentive_rate / 100));
    // 점수 1점당 추가 가산액 (만원)
    const 점당_가산액_만원 = (point: number) => Math.round(annual_revenue_billion * 10000 * ((CP_운영_가산율_최대 * point) / 100 / 100));

    // Gap 분석 처방전 도출 (점수 누락 항목 분석)
    const action_items: 시뮬레이션_결과_보고서['개선_처방전_목록'] = [];

    // 전담인력 미지정 시
    if (!checklist.전담인력_지정) {
      const point_gain = 3.1;
      action_items.push({
        항목명: 'CP 전담 또는 겸임 인력 지정 증빙',
        현재상태: '부서 내 담당 인력 미지정 또는 직무 6개월 미충족',
        권고조치: scale.includes('초과')
          ? '원 직제규정 부서 내 의료인 전담 1명 필수 지정 및 직무기술서 구비'
          : 'CP 해당 부서 내 겸임 인력(부서장 포함) 최소 기준 충족 및 발령 공문 구비',
        예상_추가점수: point_gain,
        예상_추가재정_만원: 점당_가산액_만원(point_gain),
      });
    }

    // 유형별 Branch CP 미개발 시 (최대 감점 요인)
    if (!checklist.유형별_Branch_CP_개발) {
      const point_gain = 3.1;
      action_items.push({
        항목명: '유형별 CP (Branch CP) 개발 및 적용',
        현재상태: '단일 CP만 운영 중 (운영평가 지침상 유형별 CP 개발 여부 평가)',
        권고조치: '대표 CP에 대해 소아/일반, 단측/양측, 당뇨·고혈압 동반군 등 유형별 분기 프로토콜 전산 반영',
        예상_추가점수: point_gain,
        예상_추가재정_만원: 점당_가산액_만원(point_gain),
      });
    }

    // 운영 CP 수 부족 시
    if (usage.운영_CP_개수 < min_cp) {
      const missing = min_cp - usage.운영_CP_개수;
      const point_gain = Math.round((20 - apply_status_score) * 10) / 10;
      action_items.push({
        항목명: `병상 규모별 최소 운영 CP 질환 수 (${min_cp}개) 충족`,
        현재상태: `현재 ${usage.운영_CP_개수}개 운영 (${missing}개 부족)`,
        권고조치: `국립중앙의료원 공공의료 CP(2025년까지 누적 신규 71개) 중 다빈도 질환을 추가 도입하여 ${min_cp}개 이상 운영`,
        예상_추가점수: point_gain,
        예상_추가재정_만원: 점당_가산액_만원(point_gain),
      });
    }

    // 인센티브 규정 미보유 시
    if (!checklist.의료진_인센티브_규정) {
      action_items.push({
        항목명: 'CP 참여 의료진 원내 인센티브 제도 수립',
        현재상태: 'CP 개발 및 적용 관련 전용 인센티브 규정 부재',
        권고조치: 'QI 일반 장려금이 아닌 순수 CP 활동 인센티브 지급 규정 제정 및 실적 증빙',
        예상_추가점수: 3.1,
        예상_추가재정_만원: 점당_가산액_만원(3.1),
      });
    }

    // 대표 5개 모니터링 미실시 시
    if (!usage.대표_5개_CP_지표평가_보고) {
      action_items.push({
        항목명: '대표 5개 CP 성과 모니터링 지표 정기 보고',
        현재상태: '재원일수, 항생제 일수, 합병증 등 전후 성과지표 미제출',
        권고조치: '대표 5개 질환에 대해 CP 적용 전 실적, 개선 목표, CP 적용 후 실적 통계 산출 및 공문 보고',
        예상_추가점수: 15.0,
        예상_추가재정_만원: 점당_가산액_만원(15),
      });
    }

    return {
      병원_규모: scale,
      최소_필요_CP_개수: min_cp,
      전담인력_요건_충족: checklist.전담인력_지정,
      개발_영역_점수: dev_score,
      적용_영역_점수: apply_score,
      종합_운영평가_점수: total_score,
      운영평가_예상_등급: grade,
      적용률_퍼센트: apply_rate,
      완료율_퍼센트: complete_rate,
      질환별_관리율_퍼센트: mgmt_rate,
      신포괄_정책가산율: incentive_rate,
      연간_신포괄_진료비_억원: annual_revenue_billion,
      연간_예상_수가_가산금액_만원: annual_incentive_ten_thousand_won,
      개선_처방전_목록: action_items,
    };
  }
}
