export interface 거점_위치 {
  거점: string;
  위도: number;
  경도: number;
  시도명: string;
  시군구명: string | null; // 광역시 단위 거점이면 null
}

/** 질문에 들어 있는 거점(긴 이름 우선)을 찾는다 */
export function 거점_찾기(질문: string): 거점_위치 | null {
  const 이름 = Object.keys(전국_주요_거점_좌표).sort((a, b) => b.length - a.length).find((k) => 질문.includes(k));
  if (!이름) return null;
  const info = 전국_주요_거점_좌표[이름];
  const [시도명, 시군구] = info.지역명.replace(/\s*\(.*\)$/, '').split(/\s+/);
  return { 거점: 이름, 위도: info.좌표[0], 경도: info.좌표[1], 시도명, 시군구명: 시군구 && !시군구.includes('/') ? 시군구 : null };
}
