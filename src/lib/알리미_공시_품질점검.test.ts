import { describe, it, expect } from 'vitest';
import { 알리미_공시_자동점검, 알리미_점검_규칙_목록 } from './알리미_공시_품질점검';

describe('알리미 실제 공시 자동점검', () => {
  const 결과 = 알리미_공시_자동점검();
  const 건수 = (규칙: string) => 결과.filter((r) => r.규칙 === 규칙);

  it('재무상태표 항등식 불일치는 2021년 부산·서산·서귀포 3건', () => {
    expect(건수('bs').map((r) => `${r.기관명} ${r.연도}`)).toEqual(['부산의료원 2021', '서산의료원 2021', '서귀포의료원 2021']);
  });

  it('손익 항등식은 모두 성립', () => {
    expect(건수('pl')).toEqual([]);
  });

  it('결산 미공시: 서울적십자 2021~2024, 상주적십자 2021·2024', () => {
    expect(건수('missing').map((r) => `${r.기관명} ${r.연도}`)).toEqual([
      '서울적십자병원 2021',
      '서울적십자병원 2022',
      '서울적십자병원 2023',
      '서울적십자병원 2024',
      '상주적십자병원 2021',
      '상주적십자병원 2024',
    ]);
  });

  it('인건비 0원 공시: 수원 2021, 강릉·공주 2025, 목포 2024·2025', () => {
    expect(건수('payroll0').map((r) => `${r.기관명} ${r.연도}`).sort()).toEqual(
      ['경기도의료원 수원병원 2021', '강릉의료원 2025', '공주의료원 2025', '목포시의료원 2024', '목포시의료원 2025'].sort()
    );
  });

  it('모든 결과는 등록된 규칙에 속한다', () => {
    const ids = new Set(알리미_점검_규칙_목록.map((r) => r.id));
    for (const r of 결과) expect(ids.has(r.규칙)).toBe(true);
    expect(건수('staff').length).toBeGreaterThan(0);
  });
});
