/**
 * 시·군·구 기본 정보 및 필수의료 원천 지표 인터페이스
 */
export interface 시군구_원천_데이터 {
  시도코드: string;
  시도명: string;
  시군구코드: string;
  시군구명: string;
  인구수: number;
  // 1. 응급의료 지표
  응급_60분_미도달_인구비율: number; // 권역응급센터 60분 내 미도달 인구 비율(%)
  관내_응급_의료이용률: number;     // 관내 중증응급환자 의료이용률(RI, %)
  // 2. 분만·모자의료 지표
  분만_60분_미도달_인구비율: number; // 분만실 60분 내 미도달 인구 비율(%)
  관내_분만율: number;               // 분만 관내이용률(RI, %) — 헬스맵 CBD01
  // 3. 소아·중증진료 지표 (실데이터 미확보 시 null → 소아 분야 진단 제외)
  소아_병상_공급비율: number | null;         // 기준 병상 대비 공급 비율(%)
  소아_야간휴일_접근성지수: number | null;  // 소아청소년과 야간/휴일 진료 접근성 지수 (0~100)
  // 4. 인력 및 병상 인프라 (선택적)
  인구_천명당_의사수?: number;
  인구_천명당_병상수?: number;
}

