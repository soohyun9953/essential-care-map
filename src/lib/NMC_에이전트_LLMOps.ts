export interface 평가_결과 {
  사례: string;
  통과: boolean;
  근거: string;
}

/** 시험평가(Evals): 템플릿별 사례를 실제 플랫폼 함수로 실행 */
export function 에이전트_평가(템플릿: 에이전트_템플릿_종류, 지식베이스: string[]): 평가_결과[] {
  if (템플릿 === '질의응답') {
    const 사례 = [
      { q: '달빛어린이병원 운영시간', 기대: '달빛어린이병원' },
      { q: '분만취약지 산부인과 지원 금액', 기대: '분만취약지' },
      { q: '응급의료취약지 선정 기준', 기대: '응급의료' },
      { q: 'CP 운영 가산율', 기대: '신포괄' },
      { q: '퇴원환자 지역사회 연계 수가', 기대: '퇴원' },
    ];
    return 사례.map(({ q, 기대 }) => {
      const top = 경량_RAG_엔진.retrieve(q, 8).filter((x) => 지식베이스.length === 0 || 지식베이스.includes(x.청크.분류))[0];
      const 통과 = Boolean(top && top.청크.문서명.includes(기대));
      return { 사례: q, 통과, 근거: top ? `1순위 문서: ${top.청크.문서명}` : '선택한 지식베이스에서 문서를 찾지 못함' };
    });
  }
  if (템플릿 === '문서초안') {
    const 초안 = 정책_요구자료_초안('보건복지부', '필수의료 취약지 현황');
    return ['## 1. 필수의료 취약지 현황', '## 2. 시도별', '## 3. 유의사항', '초안입니다'].map((필수) => ({
      사례: `요구자료 초안에 「${필수.replace('## ', '')}」 포함`,
      통과: 초안.includes(필수),
      근거: 초안.includes(필수) ? '포함됨' : '누락',
    }));
  }
  if (템플릿 === '자료검증') {
    const 결과 = 알리미_공시_자동점검().filter((x) => x.규칙 === 'bs').map((x) => `${x.기관명} ${x.연도}`);
    return ['부산의료원 2021', '서산의료원 2021', '서귀포의료원 2021'].map((기대) => ({
      사례: `재무상태표 항등식 불일치 탐지: ${기대}`,
      통과: 결과.includes(기대),
      근거: 결과.includes(기대) ? '탐지됨' : '탐지 못함',
    }));
  }
  return ['강원특별자치도 응급취약 시군구', '분만 A등급 시군구', '의료이익률 하위 5개 지방의료원'].map((q) => {
    const r = 자연어_질의(q);
    const 통과 = 'sql' in r && r.행.length > 0;
    return { 사례: `자동 질의: ${q}`, 통과, 근거: 'sql' in r ? `${r.행.length}행 반환` : r.오류 };
  });
}

