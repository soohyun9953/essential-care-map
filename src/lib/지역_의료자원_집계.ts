// 시군구별 보유 의료자원을 내장 기관 목록에서 집계 (추정값 없음)
// - 공공의료기관·병상: 공공의료기관 데이터셋 (시군구코드 일치)
// - 응급의료기관: E-Gen 응급의료기관 목록 (주소 일치)
// - 분만 가능 기관: 심평원 분만가능 의료기관 목록 (주소 일치, 청구 실적 기준)
// - 달빛어린이병원: 국립중앙의료원 목록 (주소 일치)

import { 전국_공공의료기관_목록 } from './공공의료기관_데이터셋';
import { 응급의료기관_목록 } from './응급의료기관_데이터셋';
import { 분만가능_의료기관_목록 } from './분만가능_의료기관_데이터셋';
import { 달빛어린이병원_목록 } from './달빛어린이병원_데이터셋';

const 시도_약칭: Record<string, string> = {
  충청북도: '충북', 충청남도: '충남', 전라북도: '전북', 전북특별자치도: '전북', 전라남도: '전남',
  경상북도: '경북', 경상남도: '경남', 강원도: '강원', 강원특별자치도: '강원',
};
const 약칭 = (시도: string) => 시도_약칭[시도] ?? 시도.slice(0, 2);

// 2026년 행정구역 개편으로 주소에 새 이름이 쓰이는 경우 (진단 데이터는 개편 전 이름)
const 주소_시도_별칭: Record<string, string[]> = { 전남광주통합특별시: ['광주', '전남'] };
const 인천_구_별칭: Record<string, string[]> = {
  서구: ['서구', '서해구', '검단구'],
  중구: ['중구', '영종구', '제물포구'],
  동구: ['동구', '제물포구'],
};

/** 주소가 해당 시도·시군구에 속하는지 (예: '강원특별자치도 영월군 …', '경기도 수원시 장안구 …') */
export function 주소_지역_일치(시도명: string, 시군구명: string, 주소: string): boolean {
  const [주소_시도, ...나머지] = 주소.split(/\s+/);
  if (!주소_시도) return false;
  const 대상 = 약칭(시도명);
  const 후보 = 주소_시도_별칭[주소_시도] ?? [약칭(주소_시도)];
  if (!후보.includes(대상)) return false;
  if (시군구명 === 시도명) return true; // 세종특별자치시
  const 앞부분 = 나머지.slice(0, 3);
  return 시군구명.split(/\s+/).every((토큰) => {
    const 별칭 = 대상 === '인천' ? 인천_구_별칭[토큰] ?? [토큰] : [토큰];
    return 별칭.some((b) => 앞부분.includes(b));
  });
}

export interface 지역_의료자원 {
  공공의료기관_수: number;
  공공의료기관_병상: number;
  응급의료기관: { 기관명: string; 분류: string }[];
  분만기관_수: number;
  야간분만기관_수: number;
  달빛어린이병원_수: number;
}

export function 지역_의료자원_집계(시도명: string, 시군구명: string, 시군구코드: string): 지역_의료자원 {
  const 공공 = 전국_공공의료기관_목록.filter((h) => h.시군구코드 === 시군구코드);
  const 분만 = 분만가능_의료기관_목록.filter((h) => 주소_지역_일치(시도명, 시군구명, h.주소));
  return {
    공공의료기관_수: 공공.length,
    공공의료기관_병상: 공공.reduce((acc, h) => acc + h.병상수, 0),
    응급의료기관: 응급의료기관_목록
      .filter((h) => 주소_지역_일치(시도명, 시군구명, h.주소))
      .map((h) => ({ 기관명: h.기관명, 분류: h.분류 })),
    분만기관_수: 분만.length,
    야간분만기관_수: 분만.filter((h) => h.야간).length,
    달빛어린이병원_수: 달빛어린이병원_목록.filter((h) => 주소_지역_일치(시도명, 시군구명, h.주소)).length,
  };
}
