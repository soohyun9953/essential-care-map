const 시군구_어간 = (이름: string) => (이름.length > 2 && /[시군구]$/.test(이름) ? 이름.slice(0, -1) : 이름);

/** 질문에서 시군구를 찾는다 (긴 이름 우선, '영월' 같은 어간도 인정, 같은 이름이면 질문의 시도명으로 구분) */
export function 질문_지역_찾기(질문: string) {
  const 후보 = [...전국_시군구_진단_데이터].sort((a, b) => b.시군구명.length - a.시군구명.length);
  const 고르기 = (목록: typeof 후보) => 목록.find((r) => 질문.includes(r.시도명.slice(0, 2))) ?? 목록[0] ?? null;
  const 이름일치 = 후보.filter((r) => 질문.includes(r.시군구명));
  if (이름일치.length) return 고르기(이름일치.filter((r) => r.시군구명 === 이름일치[0].시군구명));
  const 어간일치 = 후보.filter((r) => 시군구_어간(r.시군구명).length >= 2 && 질문.includes(시군구_어간(r.시군구명)));
  return 어간일치.length ? 고르기(어간일치.filter((r) => r.시군구명 === 어간일치[0].시군구명)) : null;
}

/** 시군구 대표 좌표 (플랫폼 내장). 광역시의 같은 이름 구는 '대구중구'처럼 시 이름을 붙인 키로 찾는다 */
export function 시군구_기준점(시도명: string, 시군구명: string): { 위도: number; 경도: number } | null {
  const 광역시 = /광역시$/.test(시도명);
  const 키들 = 광역시 ? [`${시도명.slice(0, 2)}${시군구명}`, `${시군구명}(${시도명.slice(0, 2)})`] : [시군구명];
  if (!광역시 || 시도명.startsWith('서울')) 키들.push(시군구명);
  for (const 키 of 키들) {
    const c = 전국_시군구_대표_좌표[키];
    if (c) return { 위도: c[0], 경도: c[1] };
  }
  return null;
}

function 거리_km(a: { 위도: number; 경도: number }, b: { 위도: number; 경도: number }) {
  const R = 6371;
  const dLat = ((b.위도 - a.위도) * Math.PI) / 180;
  const dLon = ((b.경도 - a.경도) * Math.PI) / 180;
  const x = Math.sin(dLat / 2) ** 2 + Math.cos((a.위도 * Math.PI) / 180) * Math.cos((b.위도 * Math.PI) / 180) * Math.sin(dLon / 2) ** 2;
  return 2 * R * Math.atan2(Math.sqrt(x), Math.sqrt(1 - x));
}


const 공백제거 = (s: string) => s.replace(/\s/g, '');

export function 공개정보_안내(질문_원문: string): 안내_답변 {
  const 질문 = 질문_원문.trim();
  const 압축 = 공백제거(질문);

  // ② 알리미 공시 기관 (기관명이 질문에 있으면)
  const 공시 = 알리미_기관_공시_목록.find((h) => 압축.includes(공백제거(h.기관명)) || 압축.includes(공백제거(h.기관명).replace(/^경기도의료원/, '')));
  if (공시) {
    const r = 최근_결산연도(공시);
    const 감면 = 공시.감면액;
    return {
      유형: '공공병원',
      제목: `${공시.기관명} 공개 정보`,
      내용: [
        r ? `의사 ${r.의사직_현원 ?? '-'}명, 간호사 ${r.간호직_현원 ?? '-'}명 (직종별 현원, ${r.연도}년)` : '인력 공시 없음',
        r && r.의료수익 !== null ? `의료수익 ${(Math.round(r.의료수익 / 10000) / 10).toLocaleString()}억원 (${r.연도}년 결산)` : '결산 공시 없음',
        감면 && 감면.취약계층_감면총액_원 !== null
          ? `취약계층 진료비 감면 ${Math.round(감면.취약계층_감면총액_원 / 10000).toLocaleString()}만원 (${감면.기준일 ?? ''} 기준, 일반진료비 감면율 ${감면.취약계층_일반진료비_율 ?? '-'}%)`
          : '취약계층 감면 공시 없음',
        '자세한 경영·인력 공시는 알리미 원문에서 확인할 수 있습니다.',
      ],
      출처: [{ 자료: `${알리미_공시_출처.기관} ${알리미_공시_출처.자료명}`, 상세: `수집 ${알리미_공시_출처.수집일시}`, URL: 알리미_공시_출처.URL }],
    };
  }

  // ① 지역·거점 기준 기관 찾기
  // 시군구가 없는 시도 단위 거점('대구' 등)보다 질문의 시군구('대구 중구')를 우선한다
  const 찾은_거점 = 거점_찾기(질문);
  const 질문_지역 = 질문_지역_찾기(질문);
  const 거점 = 찾은_거점 && !찾은_거점.시군구명 && 질문_지역 ? null : 찾은_거점;
  const 지역 = 거점?.시군구명
    ? 전국_시군구_진단_데이터.find((r) => r.시도명 === 거점.시도명 && r.시군구명 === 거점.시군구명) ?? 질문_지역
    : 질문_지역;
  const nicu = /NICU|니큐|신생아\s*(중환자|집중)|미숙아|인큐베이터/i.test(질문);
  const 응급 = /응급|응급실|다쳤|사고/.test(질문);
  const 분만 = !nicu && /분만|출산|산부인과|임신|산모/.test(질문);
  const 달빛 = !nicu && /달빛|소아|아이|어린이|야간 진료|휴일 진료/.test(질문);
  const 제도질문 = /뭐야|무엇|어떻게|지원|제도|기준|란\b|이란/.test(질문);

  // 기준점: 역·공항 좌표 → 시군구 대표 좌표 → (없으면) 관내 응급의료기관 평균 위치
  //   예전엔 관내 응급실 평균 위치만 써서, 응급실이 1곳인 군은 그 병원이 기준점이 되어 '직선 0.0km'로 나왔다
  const 기준 = (() => {
    if (거점) return { 위도: 거점.위도, 경도: 거점.경도, 이름: 거점.거점, 설명: `${거점.거점} 좌표` };
    if (!지역) return null;
    const 대표 = 시군구_기준점(지역.시도명, 지역.시군구명);
    if (대표) return { ...대표, 이름: 지역.시군구명, 설명: `${지역.시군구명} 대표 좌표 (플랫폼 내장)` };
    const 관내 = 응급의료기관_목록.filter((h) => h.위도 !== null && h.경도 !== null && 주소_지역_일치(지역.시도명, 지역.시군구명, h.주소));
    if (!관내.length) return null;
    return {
      위도: 관내.reduce((a, h) => a + (h.위도 as number), 0) / 관내.length,
      경도: 관내.reduce((a, h) => a + (h.경도 as number), 0) / 관내.length,
      이름: `${지역.시도명} ${지역.시군구명}`,
      설명: `${지역.시군구명} 관내 응급의료기관 평균 위치`,
    };
  })();
  // 거리·정렬은 원자료에 없는 플랫폼 계산이므로 출처에 따로 밝힌다
  const 거리_출처: 안내_출처 | null = 기준 ? { 자료: '직선 거리·가까운 순 정렬 (플랫폼 계산)', 상세: `기준점: ${기준.설명}. 도로 거리·이동 시간과 다를 수 있음` } : null;
  const 위치명 = 거점 ? `${거점.거점} 근처` : 지역 ? `${지역.시도명} ${지역.시군구명}` : '';
  const egen_출처: 안내_출처 = { 자료: `${응급의료기관_출처.기관} ${응급의료기관_출처.자료명}`, 상세: `수집 ${응급의료기관_출처.수집일}`, URL: 응급의료기관_출처.URL };

  if (nicu && 기준) {
    const 후보 = 응급의료기관_목록
      .filter((h) => /권역응급의료센터|지역응급의료센터/.test(h.분류) && h.위도 !== null && h.경도 !== null)
      .map((h) => ({ h, km: 거리_km(기준, { 위도: h.위도 as number, 경도: h.경도 as number }) }))
      .sort((a, b) => a.km - b.km)
      .slice(0, 5);
    return {
      유형: '기관찾기',
      제목: `${위치명} 신생아중환자실(NICU) 확인 대상 병원`,
      내용: [
        'NICU를 운영하는 병원의 공식 공개 목록은 없어, 가까운 권역·지역응급의료센터를 거리순으로 보여드립니다. NICU 운영·빈 병상 여부는 아래 실시간 정보나 병원 전화로 확인하세요.',
        ...후보.map((x, i) => `${i + 1}. ${x.h.기관명} (${x.h.분류}, 직선 ${x.km.toFixed(1)}km) ☎ ${x.h.응급실전화 || x.h.대표전화}`),
      ],
      출처: [egen_출처, ...(거리_출처 ? [거리_출처] : [])],
      실시간_확인: 후보
        .map((x) => {
          const 지 = 주소_시군구(x.h.주소);
          return 지 ? { ...지, 기관명: x.h.기관명 } : null;
        })
        .filter((x): x is { 시도명: string; 시군구명: string; 기관명: string } => x !== null),
    };
  }

  if (기준 && (응급 || 분만 || 달빛) && !제도질문) {
    const 가까운순 = <T extends { 위도: number | null; 경도: number | null }>(목록: T[], n: number) =>
      목록
        .filter((h) => h.위도 !== null && h.경도 !== null)
        .map((h) => ({ h, km: 거리_km(기준, { 위도: h.위도 as number, 경도: h.경도 as number }) }))
        .sort((a, b) => a.km - b.km)
        .slice(0, n);
    const 내용: string[] = [];
    const 출처: 안내_출처[] = [];
    if (응급) {
      const 목록 = 가까운순(응급의료기관_목록, 5);
      내용.push(`응급실 (가까운 순):`);
      목록.forEach(({ h, km }) => 내용.push(`· ${h.기관명} (${h.분류}, 직선 ${km.toFixed(1)}km) ☎ ${h.응급실전화 || h.대표전화}`));
      출처.push(egen_출처);
    }
    if (분만) {
      const 목록 = 가까운순(분만가능_의료기관_목록, 5);
      내용.push(`분만 가능 의료기관 (가까운 순, 청구 실적 기준):`);
      목록.forEach(({ h, km }) => 내용.push(`· ${h.기관명} (${h.종별}${h.야간 ? ', 야간 분만 실적 있음' : ''}, 직선 ${km.toFixed(1)}km) ☎ ${h.전화번호}`));
      출처.push({ 자료: `${분만가능_의료기관_출처.기관} ${분만가능_의료기관_출처.자료명}`, 상세: `${분만가능_의료기관_출처.산출기간}, 기준일 ${분만가능_의료기관_출처.기준일}`, URL: 분만가능_의료기관_출처.URL });
      내용.push('※ 청구 실적 기준 목록이므로 방문 전 병원에 분만 가능 여부를 확인하세요.');
    }
    if (달빛) {
      const 목록 = 가까운순(달빛어린이병원_목록, 3);
      내용.push(`달빛어린이병원 (소아 야간·휴일 진료, 가까운 순):`);
      목록.forEach(({ h, km }) => 내용.push(`· ${h.기관명} (직선 ${km.toFixed(1)}km) ☎ ${h.대표전화}`));
      출처.push({ 자료: `${달빛어린이병원_출처.기관} ${달빛어린이병원_출처.자료명}`, 상세: `수집 ${달빛어린이병원_출처.수집일}`, URL: 달빛어린이병원_출처.URL });
    }
    if (거리_출처) 출처.push(거리_출처);
    return { 유형: '기관찾기', 제목: 위치명, 내용, 출처 };
  }

  // ③ 제도 설명: 원문을 확인한 지침 문서만 검색
  //   검색 점수에는 기본점(15)이 있어 무관한 질문도 걸리므로, 핵심 키워드가 실제로 겹치고 기본점보다 충분히 높을 때만 쓴다
  const 후보 = 경량_RAG_엔진
    .retrieve(질문, 8)
    .filter((x) => (x.청크.검증상태 === '원문 확인' || x.청크.검증상태 === '일부 확인') && !x.청크.문서명.includes('지표정의서') && x.매칭_키워드.length > 0 && x.유사도_점수 >= 20);
  // 최고 점수의 70% 이상인 문서만 함께 보여준다 (관련 낮은 문서가 섞이지 않게)
  const 결과 = 후보.filter((x) => x.유사도_점수 >= (후보[0]?.유사도_점수 ?? 0) * 0.7).slice(0, 2);
  if (결과.length) {
    return {
      유형: '제도안내',
      제목: 결과[0].청크.문서명,
      내용: 결과.map((x) => x.청크.본문),
      출처: 결과.map((x) => ({
        자료: x.청크.문서명,
        상세: `${x.청크.조항_페이지} · ${x.청크.검증상태 ?? '검증 상태 미표시'}${x.청크.검증_근거 ? ` — ${x.청크.검증_근거}` : ''}`,
      })),
    };
  }

  return {
    유형: '찾지못함',
    제목: '관련 공개 자료를 찾지 못했습니다',
    내용: ['지역명이나 역·공항 이름과 함께 응급실·분만·달빛어린이병원·NICU를 물어보거나, 공공병원 이름이나 제도 이름으로 다시 질문해주세요.'],
    출처: [],
  };
}
