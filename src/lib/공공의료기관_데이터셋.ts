/**
 * 특정 시군구코드에 속한 공공의료기관 목록 반환
 */
export function get_public_hospitals_by_sigungu(sigungu_code: string): 공공의료기관_정보[] {
  return 전국_공공의료기관_목록.filter((h) => h.시군구코드 === sigungu_code);
}

/**
 * 특정 시도명에 속한 공공의료기관 목록 반환
 */
export function get_public_hospitals_by_sido(sido_name: string): 공공의료기관_정보[] {
  return 전국_공공의료기관_목록.filter((h) => h.시도명.includes(sido_name) || sido_name.includes(h.시도명));
}

/**
 * 특정 시군구에 공공병원이 없을 경우, 가장 가까운 인접 진료권/시도의 거점 공공병원 추천
 */
export function get_nearest_public_hospital(sido_name: string, sigungu_name: string, sigungu_code?: string): {
  is_local: boolean;
  hospital: 공공의료기관_정보;
} {
  // 1. 관내(해당 시군구) 공공병원 우선 검색
  if (sigungu_code) {
    const local = get_public_hospitals_by_sigungu(sigungu_code);
    if (local.length > 0) {
      // 권역이나 지역거점 우선
      const primary = local.find(h => h.그룹 === '지역' || h.그룹 === '권역') || local[0];
      return { is_local: true, hospital: primary };
    }
  }

  // 2. 시군구명으로 매칭
  const by_sigungu = 전국_공공의료기관_목록.filter(h => h.시군구명 === sigungu_name);
  if (by_sigungu.length > 0) {
    const primary = by_sigungu.find(h => h.그룹 === '지역' || h.그룹 === '권역') || by_sigungu[0];
    return { is_local: true, hospital: primary };
  }

  // 3. 관내에 없으면 동일 시도 내 '지역' 또는 '권역' 거점 공공의료기관 추천
  const sido_hospitals = get_public_hospitals_by_sido(sido_name);
  const regional = sido_hospitals.filter(h => h.그룹 === '지역');
  if (regional.length > 0) {
    return { is_local: false, hospital: regional[0] };
  }
  const zonal = sido_hospitals.filter(h => h.그룹 === '권역');
  if (zonal.length > 0) {
    return { is_local: false, hospital: zonal[0] };
  }
  if (sido_hospitals.length > 0) {
    return { is_local: false, hospital: sido_hospitals[0] };
  }

  // 4. 전국 대표 (국립중앙의료원)
  const nmc = 전국_공공의료기관_목록.find(h => h.기관명.includes('국립중앙의료원')) || 전국_공공의료기관_목록[0];
  return { is_local: false, hospital: nmc };
}
