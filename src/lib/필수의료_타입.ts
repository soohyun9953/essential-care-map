// 필수의료 취약지 지표 진단 시스템 타입 정의 (TypeScript)

/**
 * 취약도 4단계 등급 정의
 */
export type 취약도_등급 = '정상' | '관찰' | '취약' | '심각';

/**
 * 취약도 테마 색상 및 뱃지 정보
 */
export interface 취약도_메타정보 {
  등급: 취약도_등급;
  라벨: string;
  색상코드: string;
  배경색상_클래스: string;
  텍스트색상_클래스: string;
  설명: string;
}

/**
 * 시·군·구 기본 정보 및 필수의료 원천 지표 인터페이스
 */
export interface 시군구_원천_데이터 {
  시도코드: string;
  시도명: string;
  시군구코드: string;
  시군구명: string;
  인구수: number;
  // 1. 응급의료 지표
  응급_60분_미도달_인구비율: number; // 권역응급센터 60분 내 미도달 인구 비율(%)
  관내_응급_의료이용률: number;     // 관내 중증응급환자 의료이용률(RI, %)
  // 2. 분만·모자의료 지표
  분만_60분_미도달_인구비율: number; // 분만실 60분 내 미도달 인구 비율(%)
  관내_분만율: number;               // 가임기 여성 인구 대비 관내 분만율(%)
  // 3. 소아·중증진료 지표
  소아_병상_공급비율: number;         // 기준 병상 대비 공급 비율(%)
  소아_야간휴일_접근성지수: number;  // 소아청소년과 야간/휴일 진료 접근성 지수 (0~100)
}

/**
 * 필수의료 3대 취약지 진단 결과 인터페이스
 */
export interface 필수의료_진단_결과 {
  // 기본 식별 정보
  시도코드: string;
  시도명: string;
  시군구코드: string;
  시군구명: string;
  인구수: number;

  // 원천 수치
  응급_60분_미도달_인구비율: number;
  관내_응급_의료이용률: number;
  분만_60분_미도달_인구비율: number;
  관내_분만율: number;
  소아_병상_공급비율: number;
  소아_야간휴일_접근성지수: number;

  // 3대 분야별 취약 여부 판정 (불리언)
  응급취약지역_여부: boolean;
  분만취약지역_여부: boolean;
  소아취약지역_여부: boolean;

  // 종합 판정
  취약분야_수: number; // 0 ~ 3
  종합_취약도_등급: 취약도_등급;
  종합_취약도_점수: number; // 0 ~ 100

  // 세부 판정 근거
  응급_판정근거: string;
  분만_판정근거: string;
  소아_판정근거: string;
}

