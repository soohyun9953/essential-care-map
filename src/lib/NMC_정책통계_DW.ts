import { 전국_시군구_진단_데이터 } from './시군구_데이터셋';
import { 필수의료_진단_엔진 } from './필수의료_엔진';
import { 알리미_기관_공시_목록 } from './알리미_경영공시_데이터셋';
import { 경영지표_계산, 알리미_병상수, 최근_결산연도 } from './알리미_경영지표';

export interface 시군구_행 {
  시도명: string;
  시군구명: string;
  인구수: number;
  응급_미도달률: number;
  분만_이용률: number | null;
  분만_미도달률: number;
  분만등급: string;
  응급취약: boolean;
  종합등급: string;
  종합점수: number;
}

export interface 공시_행 {
  기관명: string;
  유형: string;
  연도: number;
  병상: number | null;
  의료수익_억: number | null;
  의료이익률: number | null;
  인건비율: number | null;
  의사직: number | null;
  간호직: number | null;
}

let _시군구: 시군구_행[] | null = null;
export function 시군구_테이블(): 시군구_행[] {
  if (_시군구) return _시군구;
  _시군구 = 필수의료_진단_엔진.batch_diagnose(전국_시군구_진단_데이터).map((d) => ({
    시도명: d.시도명,
    시군구명: d.시군구명,
    인구수: d.인구수,
    응급_미도달률: d.응급_60분_미도달_인구비율,
    분만_이용률: d.분만_60분_이용률 ?? null,
    분만_미도달률: d.분만_60분_미도달_인구비율,
    분만등급: d.분만취약지_등급 ?? '해당없음',
    응급취약: d.응급취약지역_여부,
    종합등급: d.종합_취약도_등급,
    종합점수: d.종합_취약도_점수,
  }));
  return _시군구;
}

export function 공시_테이블(): 공시_행[] {
  return 알리미_기관_공시_목록.map((h) => {
    const r = 최근_결산연도(h);
    const m = r ? 경영지표_계산(r) : null;
    return {
      기관명: h.기관명,
      유형: h.유형,
      연도: r?.연도 ?? 0,
      병상: 알리미_병상수(h),
      의료수익_억: r?.의료수익 != null ? Math.round(r.의료수익 / 10000) / 10 : null,
      의료이익률: m?.의료이익률 ?? null,
      인건비율: m?.인건비율 ?? null,
      의사직: r?.의사직_현원 ?? null,
      간호직: r?.간호직_현원 ?? null,
    };
  });
}

// ---------------- 취약지 식별 ----------------
export function 취약지_요약() {
  const t = 시군구_테이블();
  const 시도별 = new Map<string, { 시군구: number; 응급취약: number; 분만A: number; 분만B: number; 심각: number }>();
  for (const r of t) {
    const s = 시도별.get(r.시도명) ?? { 시군구: 0, 응급취약: 0, 분만A: 0, 분만B: 0, 심각: 0 };
    s.시군구 += 1;
    if (r.응급취약) s.응급취약 += 1;
    if (r.분만등급 === 'A') s.분만A += 1;
    if (r.분만등급 === 'B') s.분만B += 1;
    if (r.종합등급 === '심각') s.심각 += 1;
    시도별.set(r.시도명, s);
  }
  return {
    전체: t.length,
    응급취약: t.filter((r) => r.응급취약).length,
    분만A: t.filter((r) => r.분만등급 === 'A').length,
    분만B: t.filter((r) => r.분만등급 === 'B').length,
    중복취약: t.filter((r) => r.응급취약 && r.분만등급 !== '해당없음').length,
    시도별: Array.from(시도별.entries()).map(([시도명, v]) => ({ 시도명, ...v })),
  };
}

// ---------------- Text-to-SQL (규칙 기반) ----------------
export interface 질의_결과 {
  sql: string;
  열: string[];
  행: (string | number | null)[][];
  설명: string;
}

export const 질의_예시 = [
  '강원특별자치도 응급취약 시군구',
  '분만 A등급 시군구',
  '의료이익률 하위 5개 지방의료원',
  '인건비율 상위 5개 공공병원',
  '전라남도 종합 심각 시군구',
  '시도별 응급취약 시군구 수',
];

const 공시_지표: Record<string, keyof 공시_행> = { 의료이익률: '의료이익률', 인건비율: '인건비율', 의료수익: '의료수익_억', 의사: '의사직', 간호: '간호직' };

export function 자연어_질의(질문: string): 질의_결과 | { 오류: string } {
  const q = 질문.replace(/\s+/g, ' ').trim();
  const t = 시군구_테이블();
  const 시도 = Array.from(new Set(t.map((r) => r.시도명))).find((s) => q.includes(s) || q.includes(s.slice(0, 2)));

  if (/시도별/.test(q) && /응급/.test(q)) {
    const 집계 = 취약지_요약().시도별.sort((a, b) => b.응급취약 - a.응급취약);
    return {
      sql: 'SELECT 시도명, COUNT(*) FILTER (WHERE 응급취약) AS 응급취약_시군구, COUNT(*) AS 전체\nFROM 시군구_진단 GROUP BY 시도명 ORDER BY 응급취약_시군구 DESC;',
      열: ['시도명', '응급취약 시군구', '전체'],
      행: 집계.map((s) => [s.시도명, s.응급취약, s.시군구]),
      설명: '시도별 응급의료취약지 기준 해당 시군구 수',
    };
  }
  if (/응급/.test(q) && /취약/.test(q)) {
    const 행 = t.filter((r) => r.응급취약 && (!시도 || r.시도명 === 시도)).sort((a, b) => b.응급_미도달률 - a.응급_미도달률);
    return {
      sql: `SELECT 시도명, 시군구명, 응급_미도달률\nFROM 시군구_진단\nWHERE 응급취약 = TRUE${시도 ? ` AND 시도명 = '${시도}'` : ''}\nORDER BY 응급_미도달률 DESC;`,
      열: ['시도명', '시군구명', '권역응급 60분 미도달률(%)'],
      행: 행.map((r) => [r.시도명, r.시군구명, r.응급_미도달률]),
      설명: '권역응급의료센터 60분 미도달 인구 30% 이상 시군구',
    };
  }
  const 분만 = q.match(/분만\s*([AB])\s*등급/);
  if (분만) {
    const 행 = t.filter((r) => r.분만등급 === 분만[1] && (!시도 || r.시도명 === 시도));
    return {
      sql: `SELECT 시도명, 시군구명, 분만_이용률, 분만_미도달률\nFROM 시군구_진단\nWHERE 분만등급 = '${분만[1]}'${시도 ? ` AND 시도명 = '${시도}'` : ''};`,
      열: ['시도명', '시군구명', '60분 내 분만의료 이용률(%)', '60분 접근 불가(%)'],
      행: 행.map((r) => [r.시도명, r.시군구명, r.분만_이용률, r.분만_미도달률]),
      설명: `분만취약지 ${분만[1]}등급 시군구`,
    };
  }
  const 등급 = q.match(/(심각|취약|관찰|정상)/);
  if (등급 && /시군구/.test(q)) {
    const 행 = t.filter((r) => r.종합등급 === 등급[1] && (!시도 || r.시도명 === 시도)).sort((a, b) => b.종합점수 - a.종합점수);
    return {
      sql: `SELECT 시도명, 시군구명, 종합점수\nFROM 시군구_진단\nWHERE 종합등급 = '${등급[1]}'${시도 ? ` AND 시도명 = '${시도}'` : ''}\nORDER BY 종합점수 DESC;`,
      열: ['시도명', '시군구명', '종합 취약도 점수'],
      행: 행.map((r) => [r.시도명, r.시군구명, r.종합점수]),
      설명: `종합 취약도 '${등급[1]}' 시군구`,
    };
  }
  const 지표명 = Object.keys(공시_지표).find((k) => q.includes(k));
  const 순위 = q.match(/(상위|하위)\s*(\d+)/);
  if (지표명 && 순위) {
    const col = 공시_지표[지표명];
    const n = Math.min(42, Number(순위[2]));
    const 유형 = /지방의료원/.test(q) ? '지방의료원' : /적십자/.test(q) ? '적십자병원' : null;
    const 행 = 공시_테이블()
      .filter((r) => r[col] !== null && (!유형 || r.유형 === 유형))
      .sort((a, b) => (순위[1] === '상위' ? (b[col] as number) - (a[col] as number) : (a[col] as number) - (b[col] as number)))
      .slice(0, n);
    return {
      sql: `SELECT 기관명, 연도, ${col}\nFROM 알리미_공시\n${유형 ? `WHERE 유형 = '${유형}'\n` : ''}ORDER BY ${col} ${순위[1] === '상위' ? 'DESC' : 'ASC'}\nLIMIT ${n};`,
      열: ['기관명', '연도', 지표명],
      행: 행.map((r) => [r.기관명, r.연도, r[col] as number]),
      설명: `알리미 공시 최근 결산연도 기준 ${지표명} ${순위[1]} ${n}개`,
    };
  }
  return { 오류: `지원하지 않는 질문 형식입니다. 예: ${질의_예시.slice(0, 3).join(' / ')}` };
}

// ---------------- 정책 요구자료 초안 ----------------
export function 정책_요구자료_초안(요청기관: '국회' | '보건복지부', 요청내용: string): string {
  const s = 취약지_요약();
  const 상위 = [...s.시도별].sort((a, b) => b.응급취약 - a.응급취약).slice(0, 5);
  return [
    `# ${요청기관} 요구자료 답변 (초안)`,
    `요청 내용: ${요청내용 || '필수의료 취약지 현황'}`,
    '',
    '## 1. 필수의료 취약지 현황 (헬스맵 2024, 250개 시군구)',
    `- 응급의료취약지 기준 해당(권역응급의료센터 60분 미도달 인구 30% 이상): ${s.응급취약}개`,
    `- 분만취약지: A등급 ${s.분만A}개, B등급 ${s.분만B}개`,
    `- 응급·분만 중복 취약: ${s.중복취약}개`,
    '',
    '## 2. 시도별 응급취약 시군구 상위 5',
    ...상위.map((x) => `- ${x.시도명}: ${x.응급취약}개 / 전체 ${x.시군구}개`),
    '',
    '## 3. 유의사항',
    '- 플랫폼 판정은 보건복지부 선정 기준을 헬스맵 2024 지표에 적용한 결과이며, 정부 고시 지정 명단과 다를 수 있음',
    '- 응급의료기관 30분 도달 조건과 소아 지표는 자료 미확보로 반영하지 않음',
    '',
    '※ 초안입니다. 제출 전 담당자 검토와 최신 지정 고시 대조가 필요합니다.',
  ].join('\n');
}
