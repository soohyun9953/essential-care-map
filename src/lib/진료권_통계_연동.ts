export function 초안_마크다운(제목: string, t: 진료권_통계, 섹션: 초안_섹션[]): string {
  return [
    `# ${제목}`,
    `${t.병원명} · ${t.시도명} ${t.시군구명} (초안 — 담당자 검토 필요)`,
    '',
    ...섹션.flatMap((s) => [`## ${s.제목}`, s.내용, '']),
    '## 자료 출처',
    ...진료권_통계_출처.map((x) => `- ${x}`),
  ].join('\n');
}
