//  - 이름은 공백·법인명을 지운 정규화명이 정확히 같은 기관을 먼저 찾고, 없으면 앞의 시도명을 지운 이름이 하나만 일치할 때 연결
//  - CP 적용현황 기준은 심평원 허가입원병상('24.12말)이므로 데이터셋 값과 다를 수 있음
