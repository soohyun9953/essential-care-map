import { describe, it, expect } from 'vitest';
import { 필수의료_진단_엔진 } from './필수의료_엔진';
import { 시군구_원천_데이터 } from './필수의료_타입';

// 모든 분야가 기준을 충족하는(정상) 기본 지역
const 정상_지역 = (overrides: Partial<시군구_원천_데이터> = {}): 시군구_원천_데이터 => ({
  시도코드: '51',
  시도명: '강원특별자치도',
  시군구코드: '51750',
  시군구명: '영월군',
  인구수: 37000,
  응급_60분_미도달_인구비율: 0,
  관내_응급_의료이용률: 100,
  분만_60분_미도달_인구비율: 0,
  관내_분만율: 100,
  소아_병상_공급비율: 100,
  소아_야간휴일_접근성지수: 100,
  ...overrides,
});

describe('필수의료_진단_엔진.diagnose_region - 법정 취약 기준 경계값', () => {
  it('모든 지표가 양호하면 정상 등급, 취약분야 0개', () => {
    const r = 필수의료_진단_엔진.diagnose_region(정상_지역());
    expect(r.취약분야_수).toBe(0);
    expect(r.종합_취약도_등급).toBe('정상');
    expect(r.종합_취약도_점수).toBe(0);
  });

  it('응급 60분 미도달 30% 이상이면 취약 (보건복지부 기준: 30% 이상)', () => {
    expect(필수의료_진단_엔진.diagnose_region(정상_지역({ 응급_60분_미도달_인구비율: 29.9 })).응급취약지역_여부).toBe(false);
    expect(필수의료_진단_엔진.diagnose_region(정상_지역({ 응급_60분_미도달_인구비율: 30 })).응급취약지역_여부).toBe(true);
  });

  it('관내 응급 의료이용률(RI) 30% 미만이면 응급 취약', () => {
    expect(필수의료_진단_엔진.diagnose_region(정상_지역({ 관내_응급_의료이용률: 30 })).응급취약지역_여부).toBe(false);
    expect(필수의료_진단_엔진.diagnose_region(정상_지역({ 관내_응급_의료이용률: 29.9 })).응급취약지역_여부).toBe(true);
  });

  it('분만: 60분 미도달 30% 이상 또는 관내 분만율 40% 미만이면 취약', () => {
    expect(필수의료_진단_엔진.diagnose_region(정상_지역({ 분만_60분_미도달_인구비율: 29.9 })).분만취약지역_여부).toBe(false);
    expect(필수의료_진단_엔진.diagnose_region(정상_지역({ 분만_60분_미도달_인구비율: 30 })).분만취약지역_여부).toBe(true);
    expect(필수의료_진단_엔진.diagnose_region(정상_지역({ 관내_분만율: 40 })).분만취약지역_여부).toBe(false);
    expect(필수의료_진단_엔진.diagnose_region(정상_지역({ 관내_분만율: 39.9 })).분만취약지역_여부).toBe(true);
  });

  it('소아: 병상 공급비율 60% 미만이면 취약', () => {
    expect(필수의료_진단_엔진.diagnose_region(정상_지역({ 소아_병상_공급비율: 60 })).소아취약지역_여부).toBe(false);
    expect(필수의료_진단_엔진.diagnose_region(정상_지역({ 소아_병상_공급비율: 59.9 })).소아취약지역_여부).toBe(true);
  });

  it('판정 근거 문구에 실제 수치가 반영된다', () => {
    const r = 필수의료_진단_엔진.diagnose_region(정상_지역({ 응급_60분_미도달_인구비율: 68.2, 관내_응급_의료이용률: 19.8 }));
    expect(r.응급_판정근거).toContain('68.2%');
    expect(r.응급_판정근거).toContain('19.8%');
    expect(r.응급_판정근거).toContain('동시 취약');
  });
});

describe('필수의료_진단_엔진.diagnose_region - 종합 등급', () => {
  it('취약분야 개수에 따라 관찰 → 취약 → 심각으로 올라간다', () => {
    // 각 분야를 경계값 바로 너머로만 취약하게 만들어 점수 영향 최소화
    const 응급만 = 정상_지역({ 관내_응급_의료이용률: 29.9 });
    const 응급_분만 = 정상_지역({ 관내_응급_의료이용률: 29.9, 관내_분만율: 39.9 });
    const 전부 = 정상_지역({ 관내_응급_의료이용률: 29.9, 관내_분만율: 39.9, 소아_병상_공급비율: 59.9 });

    expect(필수의료_진단_엔진.diagnose_region(응급만).종합_취약도_등급).toBe('관찰');
    expect(필수의료_진단_엔진.diagnose_region(응급_분만).종합_취약도_등급).toBe('취약');
    expect(필수의료_진단_엔진.diagnose_region(전부).종합_취약도_등급).toBe('심각');
  });

  it('취약분야가 없어도 종합 점수가 높으면 등급이 올라간다', () => {
    // 모든 지표가 기준선 안쪽이지만 전반적으로 나쁜 지역
    const r = 필수의료_진단_엔진.diagnose_region(
      정상_지역({
        응급_60분_미도달_인구비율: 29.9,
        관내_응급_의료이용률: 30,
        분만_60분_미도달_인구비율: 29.9,
        관내_분만율: 40,
        소아_병상_공급비율: 60,
        소아_야간휴일_접근성지수: 0,
      })
    );
    expect(r.취약분야_수).toBe(0);
    expect(r.종합_취약도_점수).toBeGreaterThanOrEqual(25);
    expect(r.종합_취약도_등급).not.toBe('정상');
  });

  it('종합 점수는 0~100 범위이며 소수 첫째 자리로 반올림된다', () => {
    const r = 필수의료_진단_엔진.diagnose_region(
      정상_지역({ 응급_60분_미도달_인구비율: 100, 관내_응급_의료이용률: 0, 분만_60분_미도달_인구비율: 100, 관내_분만율: 0, 소아_병상_공급비율: 0, 소아_야간휴일_접근성지수: 0 })
    );
    expect(r.종합_취약도_점수).toBeLessThanOrEqual(100);
    expect(Number.isInteger(r.종합_취약도_점수 * 10)).toBe(true);
  });
});

describe('필수의료_진단_엔진.calculate_region_statistics', () => {
  it('빈 목록이면 0으로 채운 통계를 반환한다', () => {
    const s = 필수의료_진단_엔진.calculate_region_statistics([]);
    expect(s.지역수).toBe(0);
    expect(s.구분명).toBe('전국');
  });

  it('평균·인구 합계·시도 필터가 올바르게 계산된다', () => {
    const list = 필수의료_진단_엔진.batch_diagnose([
      정상_지역({ 인구수: 1000, 응급_60분_미도달_인구비율: 10 }),
      정상_지역({ 인구수: 3000, 응급_60분_미도달_인구비율: 50 }),
      정상_지역({ 시도명: '서울특별시', 인구수: 99999, 응급_60분_미도달_인구비율: 0 }),
    ]);
    const 강원 = 필수의료_진단_엔진.calculate_region_statistics(list, '강원특별자치도');
    expect(강원.지역수).toBe(2);
    expect(강원.총인구수).toBe(4000);
    expect(강원.평균_응급_60분_미도달_인구비율).toBe(30);

    const 전국 = 필수의료_진단_엔진.calculate_region_statistics(list);
    expect(전국.지역수).toBe(3);
  });
});
