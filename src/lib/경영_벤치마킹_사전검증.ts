import { 알리미_기관_공시_목록, type 알리미_기관_공시, type 알리미_연도별_공시 } from './알리미_경영공시_데이터셋';
import { 알리미_병상수, 경영지표_계산, 최근_결산연도 } from './알리미_경영지표';

export const 비교군_병상_범위 = { 최소: 150, 최대: 250 } as const;

export interface 벤치마크_행 {
  지표: string;
  단위: string;
  우리: number | null;
  비교군_중앙값: number | null;
  비교군_평균: number | null;
  방향: '높을수록_좋음' | '낮을수록_좋음' | '참고';
  비고?: string;
}

const 비율 = (a: number | null, b: number | null) => (a === null || b === null || b === 0 ? null : Math.round((a / b) * 1000) / 10);
const 억 = (v: number | null) => (v === null ? null : Math.round(v / 10000) / 10);
const 중앙 = (xs: number[]) => {
  if (!xs.length) return null;
  const s = [...xs].sort((a, b) => a - b);
  const m = Math.floor(s.length / 2);
  return Math.round((s.length % 2 ? s[m] : (s[m - 1] + s[m]) / 2) * 10) / 10;
};
const 평균 = (xs: number[]) => (xs.length ? Math.round((xs.reduce((a, b) => a + b, 0) / xs.length) * 10) / 10 : null);

/** 같은 연도, 허가병상 150~250 지방의료원 (자기 자신 제외) */
export function 동일규모_비교군(h: 알리미_기관_공시, 연도: number) {
  return 알리미_기관_공시_목록
    .filter((x) => x.기관번호 !== h.기관번호 && x.유형 === '지방의료원')
    .filter((x) => {
      const b = 알리미_병상수(x);
      return b !== null && b >= 비교군_병상_범위.최소 && b <= 비교군_병상_범위.최대;
    })
    .map((x) => x.연도별.find((r) => r.연도 === 연도))
    .filter((r): r is 알리미_연도별_공시 => Boolean(r && r.의료수익));
}

export function 경영_벤치마킹(h: 알리미_기관_공시): { 연도: number; 비교군_수: number; 행: 벤치마크_행[] } | null {
  const r = 최근_결산연도(h);
  if (!r) return null;
  const 군 = 동일규모_비교군(h, r.연도);
  const 지표들: { 지표: string; 단위: string; 값: (x: 알리미_연도별_공시) => number | null; 방향: 벤치마크_행['방향']; 비고?: string }[] = [
    { 지표: '의료수익', 단위: '억원', 값: (x) => 억(x.의료수익), 방향: '참고' },
    { 지표: '의료이익률', 단위: '%', 값: (x) => 경영지표_계산(x).의료이익률, 방향: '높을수록_좋음' },
    { 지표: '정부·지자체 지원금 ÷ 의료수익', 단위: '%', 값: (x) => 경영지표_계산(x).지원금_비율, 방향: '참고' },
    { 지표: '인건비 지출 ÷ 의료수익', 단위: '%', 값: (x) => 경영지표_계산(x).인건비율, 방향: '낮을수록_좋음' },
    { 지표: '경상운영비 ÷ 의료수익', 단위: '%', 값: (x) => 비율(x.경상운영비, x.의료수익), 방향: '낮을수록_좋음' },
    { 지표: '사업비 ÷ 의료수익', 단위: '%', 값: (x) => 비율(x.사업비, x.의료수익), 방향: '참고' },
    { 지표: '진료과별 수익', 단위: '', 값: () => null, 방향: '참고', 비고: '알리미 공시 항목 아님 — 병원 원가자료 연계 필요' },
    { 지표: '재료비율', 단위: '', 값: () => null, 방향: '참고', 비고: '알리미 공시 항목 아님 — 손익계산서 세부 계정 연계 필요' },
  ];
  return {
    연도: r.연도,
    비교군_수: 군.length,
    행: 지표들.map((m) => {
      const vs = 군.map(m.값).filter((v): v is number => v !== null && Number.isFinite(v));
      return { 지표: m.지표, 단위: m.단위, 우리: m.값(r), 비교군_중앙값: 중앙(vs), 비교군_평균: 평균(vs), 방향: m.방향, 비고: m.비고 };
    }),
  };
}

/** 규칙 기반 경영진단 요약 (비교군 중앙값 대비) */
export function 경영진단_요약(행: 벤치마크_행[]): string[] {
  const out: string[] = [];
  for (const r of 행) {
    if (r.우리 === null || r.비교군_중앙값 === null || r.방향 === '참고') continue;
    const 차 = Math.round((r.우리 - r.비교군_중앙값) * 10) / 10;
    const 좋음 = r.방향 === '높을수록_좋음' ? 차 >= 0 : 차 <= 0;
    out.push(`${r.지표}는 ${r.우리}${r.단위}로 비교군 중앙값(${r.비교군_중앙값}${r.단위})보다 ${Math.abs(차)}${r.단위 === '%' ? '%p' : r.단위} ${차 >= 0 ? '높습니다' : '낮습니다'} — ${좋음 ? '양호' : '개선 검토'}.`);
  }
  const 지원 = 행.find((r) => r.지표.startsWith('정부·지자체'));
  if (지원?.우리 != null && 지원.비교군_중앙값 != null)
    out.push(`의료수익 대비 정부·지자체 지원금은 ${지원.우리}%(비교군 중앙값 ${지원.비교군_중앙값}%)로, 지원금 변동이 순이익에 주는 영향을 함께 점검해야 합니다.`);
  return out;
}

