import { describe, it, expect } from 'vitest';
import { 주소_지역_일치, 지역_의료자원_집계 } from './지역_의료자원_집계';

describe('지역_의료자원_집계', () => {
  it('주소의 시도·시군구가 일치해야 한다 (동명 자치구 구분)', () => {
    expect(주소_지역_일치('강원특별자치도', '영월군', '강원특별자치도 영월군 영월읍 중앙로 1')).toBe(true);
    expect(주소_지역_일치('부산광역시', '중구', '서울특별시 중구 을지로 1')).toBe(false);
    expect(주소_지역_일치('경기도', '수원시 장안구', '경기도 수원시 장안구 정조로 1')).toBe(true);
    expect(주소_지역_일치('경기도', '수원시 장안구', '경기도 수원시 팔달구 중부대로 1')).toBe(false);
    expect(주소_지역_일치('세종특별자치시', '세종특별자치시', '세종특별자치시 보듬7로 20')).toBe(true);
  });

  it('2026년 개편 주소(전남광주통합특별시, 인천 서해구)도 개편 전 지역에 연결된다', () => {
    expect(주소_지역_일치('광주광역시', '광산구', '전남광주통합특별시 광산구 첨단중앙로 1')).toBe(true);
    expect(주소_지역_일치('전라남도', '영광군', '전남광주통합특별시 영광군 영광읍 1')).toBe(true);
    expect(주소_지역_일치('인천광역시', '서구', '인천광역시 서해구 심곡로 1')).toBe(true);
  });

  it('영월군: 공공병원(영월의료원)과 응급의료기관이 집계된다', () => {
    const r = 지역_의료자원_집계('강원특별자치도', '영월군', '51750');
    expect(r.공공의료기관_수).toBeGreaterThanOrEqual(1);
    expect(r.공공의료기관_병상).toBeGreaterThan(0);
    expect(r.응급의료기관.length).toBeGreaterThanOrEqual(1);
  });
});
