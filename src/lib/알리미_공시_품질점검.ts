// 지역거점공공병원 알리미 실제 공시값(42곳·2021~2025년)에 대한 자동 품질점검
// - 플랫폼 점검 규칙으로 찾은 결과이며 국립중앙의료원의 공식 검증결과가 아니다
// - 오류의심: 회계 항등식 불일치·필수 항목 누락처럼 공시값 자체가 맞지 않는 경우
// - 검토요청: 값은 있으나 서로 다른 표의 집계가 달라 기관 확인이 필요한 경우

import { 알리미_기관_공시_목록, 알리미_공시_출처 } from './알리미_경영공시_데이터셋';

export type 알리미_점검_구분 = '오류의심' | '검토요청';

export interface 알리미_점검_규칙 {
  id: string;
  이름: string;
  구분: 알리미_점검_구분;
  설명: string;
}

export const 알리미_점검_규칙_목록: 알리미_점검_규칙[] = [
  { id: 'bs', 이름: '재무상태표 항등식', 구분: '오류의심', 설명: '자산총계 = 부채총계 + 자본총계 (천원 단위 반올림 차이 2 이하 허용)' },
  { id: 'pl', 이름: '손익계산서 항등식', 구분: '오류의심', 설명: '의료이익 = 의료수익 − 의료비용' },
  { id: 'missing', 이름: '결산 미공시', 구분: '오류의심', 설명: '해당 연도 결산서(의료수익)가 비어 있음' },
  { id: 'payroll0', 이름: '인건비 0원 공시', 구분: '오류의심', 설명: '의료수익이 있는데 수입·지출 현황의 인건비 지출이 0원' },
  { id: 'staff', 이름: '직원 수 집계 불일치', 구분: '검토요청', 설명: '「직원 현황」 직원 현원과 「직종별 상세인력」 직원수 총계가 다름 (집계 기준 차이 확인 필요)' },
];

export interface 알리미_점검_결과 {
  규칙: string; // 규칙 id
  기관명: string;
  연도: number;
  내용: string;
}

const 천원 = (v: number) => `${Math.round(v).toLocaleString()}천원`;

export function 알리미_공시_자동점검(): 알리미_점검_결과[] {
  const out: 알리미_점검_결과[] = [];
  for (const h of 알리미_기관_공시_목록) {
    for (const r of h.연도별) {
      const add = (규칙: string, 내용: string) => out.push({ 규칙, 기관명: h.기관명, 연도: r.연도, 내용 });
      if (r.자산총계 !== null && r.부채총계 !== null && r.자본총계 !== null) {
        const d = r.자산총계 - r.부채총계 - r.자본총계;
        if (Math.abs(d) > 2) add('bs', `자산 − (부채 + 자본) = ${천원(d)}`);
      }
      if (r.의료수익 !== null && r.의료비용 !== null && r.의료이익 !== null) {
        const d = r.의료수익 - r.의료비용 - r.의료이익;
        if (Math.abs(d) > 2) add('pl', `의료수익 − 의료비용 − 의료이익 = ${천원(d)}`);
      }
      if (r.의료수익 === null) add('missing', '결산서 공시값 없음');
      if (r.의료수익 !== null && r.인건비 === 0) add('payroll0', `의료수익 ${천원(r.의료수익)}, 인건비 지출 0원`);
      if (r.직원_현원 !== null && r.직원수_총계 !== null && r.직원_현원 !== r.직원수_총계)
        add('staff', `직원 현원 ${r.직원_현원}명 vs 직종별 총계 ${r.직원수_총계}명 (차이 ${r.직원수_총계 - r.직원_현원}명)`);
    }
  }
  return out;
}

export const 알리미_점검_기준 = {
  자료: `${알리미_공시_출처.자료명} (${알리미_공시_출처.공시연도}, 수집 ${알리미_공시_출처.수집일시})`,
  기관수: 알리미_기관_공시_목록.length,
  안내: '플랫폼 자동점검 규칙으로 찾은 결과이며 국립중앙의료원의 공식 검증결과가 아닙니다.',
} as const;
