import { describe, it, expect } from 'vitest';
import {
  신포괄_정책가산_시뮬레이션_엔진,
  공공병원_41개_프리셋,
  CP_개발_체크리스트,
  CP_적용_실적_입력,
} from './신포괄_정책가산_시뮬레이션_엔진';

const 체크 = (n: number): CP_개발_체크리스트 => {
  const keys: (keyof CP_개발_체크리스트)[] = [
    '전담인력_지정', '다학제_팀구성표_구비', '운영계획서_CP_명시', '의료진_인센티브_규정', 'CP_개발실적_충족',
    'CP위원회_회의록_보유', '사전조사_의무기록분석', '시범적용_3개월_실시', '유형별_Branch_CP_개발', '환자_보호자_교육제공',
    '담당자_연1회_교육이수', '환자_직원_의견반영', '관련부서_현황_공유', '신규직원_원내교육_실시', '변이_모니터링_관리', '주기적_CP_최신화_갱신',
  ];
  return Object.fromEntries(keys.map((k, i) => [k, i < n])) as unknown as CP_개발_체크리스트;
};
const 만점_적용: CP_적용_실적_입력 = { 운영_CP_개수: 10, 대상_환자건수: 100, 적용_환자건수: 100, 완료_환자건수: 100, 모니터링_보고_CP_개수: 10, 대표_5개_CP_지표평가_보고: true };

describe('신포괄 정책가산 시뮬레이션 (지침 2026.1 별표3·35쪽, CP 사업 안내 제4장)', () => {
  it('만점이면 CP 운영 가산율 1.0%, 가산수가 = 포괄수가 × 1.0%', () => {
    const r = 신포괄_정책가산_시뮬레이션_엔진.calculate('종합병원_300병상_초과', 250, 체크(16), 만점_적용);
    expect(r.종합_운영평가_점수).toBe(100);
    expect(r.신포괄_정책가산율).toBe(1.0);
    expect(r.연간_예상_수가_가산금액_만원).toBe(25000); // 250억 × 1.0% = 2.5억
  });

  it('가산율은 구간표가 아니라 점수 비례 (비례방식)', () => {
    // 개발 8/16 → 25점 + 적용 50점 = 75점 → 0.75%
    const r = 신포괄_정책가산_시뮬레이션_엔진.calculate('종합병원_300병상_초과', 100, 체크(8), 만점_적용);
    expect(r.종합_운영평가_점수).toBe(75);
    expect(r.신포괄_정책가산율).toBe(0.75);
    expect(r.연간_예상_수가_가산금액_만원).toBe(7500);
    expect(r.운영평가_예상_등급).not.toMatch(/A|B|C|D/);
  });

  it('적용현황 기준 CP 수: 15·10·7·5개', () => {
    expect(신포괄_정책가산_시뮬레이션_엔진.get_min_cp_required('종합병원_500병상_초과')).toBe(15);
    expect(신포괄_정책가산_시뮬레이션_엔진.get_min_cp_required('종합병원_300병상_초과')).toBe(10);
    expect(신포괄_정책가산_시뮬레이션_엔진.get_min_cp_required('종합병원_300병상_이하')).toBe(7);
    expect(신포괄_정책가산_시뮬레이션_엔진.get_min_cp_required('병원급')).toBe(5);
  });

  it('프리셋은 별표2 시범기관 명단 기준 (영주적십자 제외, 종별 정정)', () => {
    const 이름 = (s: string) => 공공병원_41개_프리셋.find((h) => h.이름.includes(s));
    expect(이름('영주적십자')).toBeUndefined();
    for (const s of ['포천병원', '강릉의료원', '삼척의료원']) expect(이름(s)?.규모_구분, s).not.toBe('병원급');
    for (const s of ['제주의료원', '진안군의료원', '울진군의료원', '통영적십자', '거창적십자']) expect(이름(s)?.규모_구분, s).toBe('병원급');
  });
});

describe('신포괄 프리셋 병상수 (공공의료기관 데이터셋)', () => {
  it('모든 프리셋 병상수가 데이터셋 값이고, 종합병원 규모 구분은 병상수로 다시 계산된다', () => {
    for (const p of 공공병원_41개_프리셋) expect(p.병상_출처, p.이름).toBe('공공의료기관 데이터셋 (2024)');
    const 이름 = (s: string) => 공공병원_41개_프리셋.find((h) => h.이름.includes(s))!;
    expect(이름('영월의료원').병상수).toBe(188);
    expect(이름('청주의료원').규모_구분).toBe('종합병원_300병상_초과'); // 489병상
    expect(이름('부산광역시의료원').병상수).toBe(543); // 인천광역시의료원(315)과 혼동하지 않음
    expect(이름('인천광역시의료원').병상수).toBe(315);
    expect(이름('진안군의료원').규모_구분).toBe('병원급'); // 종별은 시범기관 명단 기준 유지
  });
});
