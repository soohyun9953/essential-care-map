const 시도_접두 =
  /^(서울특별시|부산광역시|대구광역시|인천광역시|광주광역시|대전광역시|울산광역시|세종특별자치시|경기도|강원특별자치도|강원도|충청북도|충청남도|전북특별자치도|전라북도|전라남도|경상북도|경상남도|제주특별자치도)/;

// 시도명을 지우면 '의료원'만 남는 기관(부산광역시의료원·인천광역시의료원 등)은 짧은 지역명을 남겨 서로 구분
const 시도_약칭: Record<string, string> = {
  서울특별시: '서울', 부산광역시: '부산', 대구광역시: '대구', 인천광역시: '인천', 광주광역시: '광주',
  대전광역시: '대전', 울산광역시: '울산', 세종특별자치시: '세종', 경기도: '경기',
};

export function 병원명_키(name: string): string {
  const n = name.replace(/\(.*?\)/g, '').replace(/\s|주식회사|의료법인|재단법인|학교법인|사회복지법인/g, '');
  const 시도 = n.match(시도_접두)?.[0];
  if (!시도) return n;
  const 나머지 = n.slice(시도.length);
  return 나머지.startsWith('의료원') ? (시도_약칭[시도] ?? '') + 나머지 : 나머지;
}

// AI 병원진단 목록의 이름 → 각 데이터셋의 이름 (같은 기관인데 표기가 다른 경우)
const 별칭: Record<string, string> = {
  인천의료원백령도분원: '인천광역시의료원백령병원',
};

export interface 병원_실데이터 {
  공공의료기관명: string | null;
  병상수: number | null; // 공공의료기관 데이터셋
  시군구코드: string | null;
  배후_시군구: 필수의료_진단_결과 | null; // 소재 시군구의 헬스맵 2024 진단 (공식 기준 판정)
  응급의료기관_분류: string | null; // E-Gen (권역응급의료센터 / 지역응급의료센터 / 지역응급의료기관 등)
  분만가능: boolean; // 심평원 분만가능 의료기관 (2025.1~2026.4 청구 실적)
  야간분만: boolean;
  달빛어린이병원: boolean;
  입원_유출률_pct: number | null; // 2024 입원 재원일수 기준
  주요_유출지: string[];
}

function 같은기관<T extends { 기관명: string }>(list: T[], key: string): T | undefined {
  return list.find((x) => 병원명_키(x.기관명) === key);
}

export function 병원_실데이터_조회(기관명: string, 시도명: string, 시군구명: string): 병원_실데이터 {
  const 원래키 = 병원명_키(기관명);
  const key = 병원명_키(별칭[원래키] ?? 원래키);

  const 공공 = 같은기관(전국_공공의료기관_목록, key);
  const 시군구코드 =
    공공?.시군구코드 ??
    전국_시군구_진단_데이터.find((r) => r.시도명.slice(0, 2) === 시도명.slice(0, 2) && r.시군구명 === 시군구명)?.시군구코드 ??
    null;
  const 원천 = 시군구코드 ? 전국_시군구_진단_데이터.find((r) => r.시군구코드 === 시군구코드) : undefined;
  const 유출입 = 시군구코드 ? Object.values(환자_유출입_2024_데이터).find((f) => String(f.code) === 시군구코드) : undefined;
  const 분만 = 같은기관(분만가능_의료기관_목록, key);

  return {
    공공의료기관명: 공공?.기관명 ?? null,
    병상수: 공공?.병상수 ?? null,
    시군구코드,
    배후_시군구: 원천 ? 필수의료_진단_엔진.diagnose_region(원천) : null,
    응급의료기관_분류: 같은기관(응급의료기관_목록, key)?.분류 ?? null,
    분만가능: Boolean(분만),
    야간분만: Boolean(분만?.야간),
    달빛어린이병원: Boolean(같은기관(달빛어린이병원_목록, key)),
    입원_유출률_pct: 유출입 ? 유출입.outflow_rate : null,
    주요_유출지: 유출입
      ? (유출입.outflow_top ?? [])
          .filter((x) => !x.is_self)
          .slice(0, 3)
          .map((x) => `${x.dest_sido} ${x.dest_sgg}`)
      : [],
  };
}

