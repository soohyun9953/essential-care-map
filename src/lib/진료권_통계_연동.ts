export const 작성도우미_대상_병원 = ['강원특별자치도영월의료원', '근로복지공단 태백병원', '정선군립병원'] as const;
export type 작성도우미_병원 = (typeof 작성도우미_대상_병원)[number];

export interface 진료권_통계 {
  병원명: string;
  병상수: number;
  시도명: string;
  시군구명: string;
  시군구코드: string;
  인구수: number;
  자체충족률_pct: number | null; // 2024 입원 재원일수 기준 관내 이용 비율 (RI)
  유출률_pct: number | null;
  주요_유출지: { 지역: string; pct: number }[];
  진단: 필수의료_진단_결과 | null;
  수요_2023: { 인구수: number; 노인비율: number; 총_입원일수: number } | null;
  수요_2030: { 인구수: number; 노인비율: number; 총_입원일수: number } | null;
  입원일수_증감률_2030_pct: number | null;
}

export const 진료권_통계_출처 = [
  '환자 유출입: 2024 의료이용 유출입 자료 (입원 재원일수 기준)',
  '취약 판정: 헬스맵 주제도 지표 2024 + 보건복지부 응급·분만 취약지 선정 기준',
  '2030 수요: 플랫폼 추정 모형 (통계청 장래인구추계 미연계 — 참고용)',
];

export function 진료권_통계_조회(병원명: 작성도우미_병원): 진료권_통계 | null {
  const 병원 = 전국_공공의료기관_목록.find((h) => h.기관명 === 병원명);
  if (!병원) return null;
  const 원천 = 전국_시군구_진단_데이터.find((r) => r.시군구코드 === 병원.시군구코드);
  const 유출입 = Object.values(환자_유출입_2024_데이터).find((f) => String(f.code) === 병원.시군구코드);
  const 진단 = 원천 ? 필수의료_진단_엔진.diagnose_region(원천) : null;
  const 시계열 = 진단 ? 의료수요_추계_엔진.calculate_time_series_demand(진단) : [];
  const y = (연도: number) => {
    const r = 시계열.find((x) => x.연도 === 연도);
    return r ? { 인구수: r.인구수, 노인비율: r.노인비율, 총_입원일수: r.총_입원일수 } : null;
  };
  const 수요_2023 = y(2023);
  const 수요_2030 = y(2030);
  return {
    병원명: 병원.기관명,
    병상수: 병원.병상수,
    시도명: 병원.시도명,
    시군구명: 병원.시군구명,
    시군구코드: 병원.시군구코드,
    인구수: 원천?.인구수 ?? 병원.인구수,
    자체충족률_pct: 유출입 ? 유출입.ri : null,
    유출률_pct: 유출입 ? 유출입.outflow_rate : null,
    // 자기 지역(관내 이용)은 유출지가 아니므로 제외
    주요_유출지: (유출입?.outflow_top ?? [])
      .filter((o) => !o.is_self)
      .slice(0, 3)
      .map((o) => ({ 지역: `${o.dest_sido} ${o.dest_sgg}`, pct: o.pct })),
    진단,
    수요_2023,
    수요_2030,
    입원일수_증감률_2030_pct:
      수요_2023 && 수요_2030 && 수요_2023.총_입원일수 > 0
        ? Math.round(((수요_2030.총_입원일수 - 수요_2023.총_입원일수) / 수요_2023.총_입원일수) * 1000) / 10
        : null,
  };
}

const 퍼센트 = (v: number | null) => (v === null ? '자료 없음' : `${v.toFixed(1)}%`);

function 현황_문단(t: 진료권_통계): string {
  const d = t.진단;
  const 유출지 = t.주요_유출지.length ? t.주요_유출지.map((o) => `${o.지역}(${o.pct}%)`).join(', ') : '자료 없음';
  return [
    `○ 진료권: ${t.시도명} ${t.시군구명} (인구 ${t.인구수.toLocaleString()}명, 헬스맵 2024)`,
    `○ 입원 자체충족률 ${퍼센트(t.자체충족률_pct)}, 관외 유출률 ${퍼센트(t.유출률_pct)} — 주요 유출지 ${유출지} (2024 환자 유출입, 입원 재원일수 기준)`,
    d
      ? `○ 응급: 권역응급의료센터 60분 미도달 인구 ${d.응급_60분_미도달_인구비율.toFixed(1)}% → ${d.응급취약지역_여부 ? '응급의료취약지 기준 해당' : '기준 미해당'}`
      : '○ 응급: 자료 없음',
    d ? `○ 분만: ${d.분만취약지_등급 ? `분만취약지 기준 ${d.분만취약지_등급}등급 해당` : '분만취약지 기준 미해당'} (${d.분만_판정근거})` : '○ 분만: 자료 없음',
    d ? `○ 종합 취약도: ${d.종합_취약도_등급} (${d.종합_취약도_점수}점, 플랫폼 종합지표)` : '',
    t.수요_2023 && t.수요_2030
      ? `○ 2030 의료수요(플랫폼 추정·참고): 노인비율 ${t.수요_2023.노인비율}% → ${t.수요_2030.노인비율}%, 총 입원일수 ${t.입원일수_증감률_2030_pct}% 변화 예상 — 통계청 장래인구추계로 확인 필요`
      : '○ 2030 의료수요: 자료 없음',
  ]
    .filter(Boolean)
    .join('\n');
}

export interface 초안_섹션 {
  제목: string;
  내용: string;
  자동연동: boolean; // true = 진료권 통계로 채운 항목
}

